"""
Native Simplicial Investigation, Script 12:
Robustness check.

The critical-line statement at N=6 for the limit ledger
   y_lim = (-a, b, -a, -a, -a, b)
came down to the algebraic fact that
   M_x(beta, c) = (1/6) [ S_A(c) e^{-beta a} + S_B(c) e^{beta b} ]
for SOME constants S_A(c), S_B(c) depending only on c.
This was because y_s takes only TWO distinct values (-a and b) on the index set.

This is true precisely BECAUSE y_lim has only two distinct values.
Any 2-valued ledger on Z/6 -- i.e., a "bicolored" ledger that assigns one value
to some subset S ⊂ Z/6 and another to its complement -- will give an
exponential-polynomial with only 2 exponentials, hence at most 1 effective
parameter, and the zeros will arrange similarly on lines.

For a general ledger with all distinct values y_0, ..., y_5, the apex
is a 6-exponential function, and zeros will NOT in general align on a line.

So the "critical-line statement" at the limit is the result of a SYMMETRY
of the limit ledger, not a generic feature of the apex.

THIS IS THE KEY OBSERVATION: the simplicial framework's native RH question
(T0 §6.7) asks for which ARITHMETIC ledgers the zeros lie on a critical line.
The answer is: such alignment is forced by a symmetry of the ledger, and the
primorial equidistribution limit at N=6 has EXACTLY the right symmetry
(s -> -s, plus the splitting between "coprime to 6" and "shares a factor with 6").

Let's verify this by checking:
  (i) The limit ledger has only 2 distinct values, by symmetry.
  (ii) A "generic" ledger does NOT show critical-line structure.
  (iii) But ANY ledger respecting the same symmetry pattern DOES.

The relevant symmetry is the subgroup of S_6 generated by:
   sigma_1: cycle (0)(1)(2)(3)(4)(5) -- identity acting trivially on values
   sigma_2: swap 1 <-> 5 (keeps y[1] = y[5])
   sigma_3: any permutation of {0, 2, 3, 4}

The limit ledger has this symmetry. The cluster {0, 2, 3, 4} = "non-coprime-to-6"
shares value -a, and {1, 5} = "coprime to 6" shares value b.
"""

import mpmath as mp
import random
from native_simplicial_02_apex_zeros import apex, find_zeros_in_rectangle

mp.mp.dps = 30


def main():
    print("=" * 80)
    print("Robustness: does the critical-line property survive perturbation?")
    print("=" * 80)

    # Test 1: A "generic" random ledger (no symmetry)
    print("\n--- Test 1: Random ledger (no symmetry imposed) ---")
    random.seed(42)
    y_rand_raw = [random.gauss(0, 1) for _ in range(6)]
    s = sum(y_rand_raw) / 6
    y_rand = [yi - s for yi in y_rand_raw]
    y_rand = [mp.mpf(yi) for yi in y_rand]
    # Normalize to unit variance
    sigma = mp.sqrt(sum(yi**2 for yi in y_rand) / 6)
    y_rand = [yi / sigma for yi in y_rand]
    print(f"y_rand = {[mp.nstr(yi, 8) for yi in y_rand]}")
    for c in range(6):
        zeros = find_zeros_in_rectangle(
            c, y_rand, x_range=(-2, 2), y_range=(-4, 4),
            grid_x=18, grid_y=18, N=6
        )
        zeros = [z for z in zeros if abs(z) > 1e-10]
        if zeros:
            re_arr = [float(z.real) for z in zeros]
            print(f"  c={c}: {len(zeros)} zeros, Re range [{min(re_arr):+8.5f}, {max(re_arr):+8.5f}], "
                  f"mean |Re|={sum(abs(x) for x in re_arr)/len(re_arr):.5f}")
        else:
            print(f"  c={c}: no zeros found")

    # Test 2: A ledger with the SAME symmetry as y_lim but DIFFERENT values
    # y = (-a', b', -a', -a', -a', b')  for various (a', b') with 4 a' = 2 b' (centering)
    print("\n--- Test 2: Symmetric bicolored ledger (-a', b', -a', -a', -a', b') ---")
    print("    constraint: 4 a' = 2 b'  ->  b' = 2 a'  (centering)")
    for a_prime_val in [0.3, 0.5, 0.7, 1.0, 1.5]:
        a = mp.mpf(a_prime_val)
        b = 2 * a  # ensures sum is 0
        y_sym = [-a, b, -a, -a, -a, b]
        print(f"\n  a' = {mp.nstr(a, 6)}, b' = {mp.nstr(b, 6)}:")
        for c in [0, 1, 3]:  # representative
            zeros = find_zeros_in_rectangle(
                c, y_sym, x_range=(-2, 2), y_range=(-3, 3),
                grid_x=14, grid_y=14, N=6
            )
            zeros = [z for z in zeros if abs(z) > 1e-10]
            if zeros:
                re_arr = [float(z.real) for z in zeros]
                im_arr = [float(z.imag) for z in zeros]
                print(f"     c={c}: {len(zeros)} zeros, Re range [{min(re_arr):+.6f}, {max(re_arr):+.6f}]")
                # show first few
                for z in zeros[:3]:
                    print(f"       beta = {mp.nstr(z.real, 8):>14} + {mp.nstr(z.imag, 8):>14} i")

    # Closed form for general (a, b) with 4a = 2b (i.e. b = 2a):
    # M(beta, c) = (1/6)[ S_A(c) e^{-beta a} + S_B(c) e^{beta b}]
    # Same as before: for c != 0, S_A = -S_B (up to sign normalization that we computed),
    # so zero condition is e^{-beta a} = e^{beta b}, i.e. beta = -2 pi i k / (a + b).
    # With b = 2a: a + b = 3a, so spacing = 2 pi / 3a.
    # For c = 0, S_A = 4, S_B = 2, so 4 e^{-beta a} + 2 e^{beta b} = 0
    #            => e^{beta (a+b)} = -2 => beta (a+b) = log 2 + i pi (2k+1)
    #            => Re beta = log 2 / (a+b),  Im spacing 2 pi / (a+b).

    print("\n--- Closed-form predictions for symmetric bicolored ledgers (b = 2a):")
    print("    c != 0: zeros on Re(beta) = 0, spacing in Im = 2 pi / (3a)")
    print("    c == 0: zeros on Re(beta) = log(2)/(3a), Im spacing 2 pi / (3a)")
    for a_val in [0.3, 0.5, 0.7, 1.0, 1.5]:
        a = mp.mpf(a_val)
        spacing = 2 * mp.pi / (3 * a)
        Re_c0 = mp.log(2) / (3 * a)
        print(f"  a = {mp.nstr(a, 6)}: spacing = {mp.nstr(spacing, 10)},  c=0 Re line = {mp.nstr(Re_c0, 10)}")


if __name__ == "__main__":
    main()
