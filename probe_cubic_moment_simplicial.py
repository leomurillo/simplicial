"""
probe_cubic_moment_simplicial.py
=================================

Numerical probe for the cubic moment M_3(T, q) at small primorial q.

Aims:
1. Compute M_3(T, q) := sum_{chi primitive mod q} integral_0^T |L(1/2+it, chi)|^3 dt
   directly at q in {6, 30} for moderate T, via mpmath dirichlet.
2. Test whether the simplicial T9.4.1-style identity for the SECOND moment
   (Plancherel sum_chi |a_chi|^2 = Helmert side) admits an analog for the
   THIRD moment in the cubic-bilateral framework.

Note: there is NO simplicial Plancherel-style identity for |L|^3 because it
is not an L^2 inner product. The probe checks what the cubic bilateral DOES
give: an explicit weighted sum representation of sum_chi |a_chi|^2 for
COEFFICIENT VECTORS a_chi.

We focus on the second-moment factorization
  sum_chi |L(1/2+it, chi)|^2
that the cubic bilateral COULD potentially attack at modified moduli, then
compare to the trivial scaling for the third moment.
"""

import mpmath as mp
from math import gcd
import time

mp.mp.dps = 30

def primitive_characters_mod_q(q):
    """Return list of indices of primitive characters mod q (small q only)."""
    # Use mpmath's character enumeration via dirichlet.
    # mpmath's dirichlet(s, chi) takes chi as a list.
    # We enumerate Dirichlet characters mod q by brute force: a character
    # is determined by its values on a generating set of (Z/qZ)*.
    # For our small q (6, 30) we'll handcraft the character tables.
    return None  # placeholder; we'll use mpmath built-ins where possible

def euler_phi(n):
    result = n
    p = 2
    nn = n
    while p * p <= nn:
        if nn % p == 0:
            while nn % p == 0:
                nn //= p
            result -= result // p
        p += 1
    if nn > 1:
        result -= result // nn
    return result

def is_primitive_chi_mod_q(chi_vals, q):
    """Check if chi (given as values on 1..q-1) is primitive mod q.
    Crude test: chi is induced from chi' mod d (d|q, d<q) iff chi is
    periodic mod d on the units. For small q, brute force."""
    # Find conductor: smallest d|q s.t. chi factors through (Z/d)*.
    for d in range(2, q):
        if q % d == 0:
            # check if chi(a) == chi(b) whenever a â‰¡ b mod d (and gcd(a,q)=1)
            ok = True
            for a in range(1, q):
                if gcd(a, q) != 1:
                    continue
                for b in range(1, q):
                    if gcd(b, q) != 1:
                        continue
                    if (a - b) % d == 0 and chi_vals[a] != chi_vals[b]:
                        ok = False
                        break
                if not ok:
                    break
            if ok:
                return False  # factors through mod-d, so not primitive mod q
    return True

def enumerate_dirichlet_characters(q):
    """Enumerate Dirichlet characters mod q by their values on (Z/q)*.
    Returns list of dicts: chi[a] = chi(a), for a in 1..q-1, with chi(a)=0 if gcd(a,q)>1.
    """
    # Find structure of (Z/q)* as direct product of cyclic groups
    # then enumerate characters.
    units = [a for a in range(1, q) if gcd(a, q) == 1]
    n = len(units)
    # Find generators (small q only; brute force)
    # For q=6: (Z/6)* = {1, 5}, cyclic of order 2, generated by 5.
    # For q=30: (Z/30)* = {1,7,11,13,17,19,23,29}, structure (Z/2)x(Z/4).
    # General: find generators by the structure theorem.

    # Brute force: characters are homomorphisms (Z/q)* -> C*.
    # We can construct all by exhaustion: for each unit g of largest order,
    # take primitive root of unity of that order; etc.
    # Simplification: use mpmath's matrix approach.

    # Actually, the cleanest approach for small q:
    # Build the character table via brute computation.

    # Find a "smith normal form" - structure
    # For q=6: just use generator 5 (order 2)
    # For q=30: use generators 11 (order 2), 7 (order 4), and find third

    if q == 6:
        # (Z/6)* cyclic order 2, generator 5
        chars = []
        for k in range(2):  # k = 0, 1
            chi = {}
            for a in range(q):
                if gcd(a, q) != 1:
                    chi[a] = mp.mpc(0)
                else:
                    # a = 5^j mod 6, j = 0 if a=1, j=1 if a=5
                    j = 0 if a == 1 else 1
                    chi[a] = mp.exp(2j * mp.pi * k * j / 2)
            chars.append(chi)
        return chars, units
    elif q == 30:
        # (Z/30)* of order 8 â‰… Z/2 x Z/4 or similar
        # generators: let's find them by orders
        units30 = [1, 7, 11, 13, 17, 19, 23, 29]
        # Compute orders
        orders = {}
        for u in units30:
            k = 1
            v = u
            while v != 1:
                v = (v * u) % q
                k += 1
                if k > 50:
                    break
            orders[u] = k
        # 11: 11^2 = 121 = 1 mod 30 -> order 2
        # 7: 7^2 = 49 = 19 mod 30; 7^3 = 133 = 13 mod 30; 7^4 = 91 = 1 mod 30 -> order 4
        # Generators: g1 = 11 (order 2), g2 = 7 (order 4); g1*g2 covers 8 elements
        # Decompose each unit u = g1^a * g2^b
        # 11 = 11^1 7^0 -> (1, 0)
        # 7 = 11^0 7^1 -> (0, 1)
        # 7^2 = 19 -> (0, 2); 7^3 = 13 -> (0, 3); 7^4 = 1 -> (0, 0)
        # 11*7 = 77 = 17 mod 30 -> (1, 1); 11*19 = 209 = 29 -> (1, 2)
        # 11*13 = 143 = 23 mod 30 -> (1, 3)
        # So: 1=(0,0), 7=(0,1), 11=(1,0), 13=(0,3), 17=(1,1), 19=(0,2), 23=(1,3), 29=(1,2)
        decomp = {1:(0,0), 7:(0,1), 11:(1,0), 13:(0,3), 17:(1,1), 19:(0,2), 23:(1,3), 29:(1,2)}
        chars = []
        for k1 in range(2):
            for k2 in range(4):
                chi = {}
                for a in range(q):
                    if gcd(a, q) != 1:
                        chi[a] = mp.mpc(0)
                    else:
                        a1, a2 = decomp[a]
                        chi[a] = mp.exp(2j*mp.pi*(k1*a1/2 + k2*a2/4))
                chars.append(chi)
        return chars, units30

def Lchi(s, chi, q, Nterms=200):
    """Approximate L(s, chi) by partial sum + (q,N)-truncation. For Re s = 1/2,
    this is rough. We'll use mpmath's built-in lerchphi/zeta(s, a/q) via
    L(s, chi) = q^{-s} sum_{a=1}^{q-1} chi(a) zeta(s, a/q)."""
    total = mp.mpc(0)
    for a in range(1, q):
        if chi[a] == 0:
            continue
        total += chi[a] * mp.zeta(s, mp.mpf(a)/q)
    return total * mp.power(q, -s)

def is_primitive(chi, q):
    """Test primitivity of chi mod q.
    chi is primitive iff its conductor is q. Equivalent test:
    chi factors through (Z/d)* iff for all a,b in (Z/q)* with a ≡ b mod d,
    chi(a) = chi(b). For each proper divisor d|q with d<q, search for a
    pair witnessing non-factoring. If for SOME d<q chi factors, return False.
    """
    for d in range(1, q):
        if q % d != 0:
            continue
        # check if a ≡ b mod d ⟹ chi(a) = chi(b) (both coprime to q)
        ok = True
        units_q = [a for a in range(1, q) if gcd(a, q) == 1]
        # Group by (a mod d) and check chi constancy on each class
        from collections import defaultdict
        classes = defaultdict(list)
        for a in units_q:
            classes[a % d].append(a)
        for cls_vals in classes.values():
            if len(cls_vals) < 2:
                continue
            first_val = chi[cls_vals[0]]
            for a in cls_vals[1:]:
                if abs(chi[a] - first_val) > mp.mpf('1e-10'):
                    ok = False
                    break
            if not ok:
                break
        if ok:
            # chi factors through mod d  → not primitive
            return False
    return True

def compute_M_3(q, T, num_t_samples=50, use_all_chars=True):
    """Compute M_3(T, q) by sampling |L(1/2+it, chi)|^3 and Simpson-integrating
    over t in [0, T]. Set use_all_chars=True to include non-primitive chars
    (relevant for BV-style sums at primorial q where all chars contribute)."""
    chars, units = enumerate_dirichlet_characters(q)
    primitives = [chi for chi in chars if is_primitive(chi, q)]
    print(f"  q={q}: phi(q)={len(units)}, total chars={len(chars)}, primitive chars={len(primitives)}")
    if use_all_chars:
        primitives = [chi for chi in chars]  # sum over ALL chars, including non-primitive
        print(f"  USE_ALL_CHARS: summing over all {len(primitives)} characters (BV-style)")

    # Sample points
    ts = [mp.mpf(T) * j / num_t_samples for j in range(num_t_samples + 1)]
    h = T / num_t_samples

    M2 = mp.mpf(0)
    M3 = mp.mpf(0)
    M4 = mp.mpf(0)

    for chi in primitives:
        # Integrate |L|^3 via Simpson
        vals3 = []
        vals2 = []
        vals4 = []
        for t in ts:
            L = Lchi(mp.mpc(mp.mpf('0.5'), t), chi, q)
            absL = abs(L)
            vals2.append(absL**2)
            vals3.append(absL**3)
            vals4.append(absL**4)
        # Simpson's rule
        def simpson(vs, h):
            n = len(vs) - 1
            if n % 2 != 0:
                # use trapezoid for last interval
                s = vs[0] + vs[-1]
                for i in range(1, n, 2):
                    s += 4 * vs[i]
                for i in range(2, n, 2):
                    s += 2 * vs[i]
                return h * s / 3
            s = vs[0] + vs[-1]
            for i in range(1, n, 2):
                s += 4 * vs[i]
            for i in range(2, n, 2):
                s += 2 * vs[i]
            return h * s / 3

        M2 += simpson(vals2, h)
        M3 += simpson(vals3, h)
        M4 += simpson(vals4, h)

    return M2, M3, M4, len(primitives)

def main():
    print("="*78)
    print(" Probe: Cubic moment M_3(T,q) at primorial q vs simplicial framework")
    print("="*78)
    print(f" mpmath dps = {mp.mp.dps}")
    print()

    # Run at q = 6 (small primorial 2*3) and q = 30 (primorial 2*3*5)
    # T = 30 for tractability

    for q in [6, 30]:
        T = mp.mpf(30)
        print(f"  q = {q}, T = {T}")
        t0 = time.time()
        M2, M3, M4, nprim = compute_M_3(q, T, num_t_samples=40)
        elapsed = time.time() - t0
        print(f"  Computed in {elapsed:.1f}s")
        print(f"  M_2(T={T}, q={q}) = {mp.nstr(M2, 10)}")
        print(f"  M_3(T={T}, q={q}) = {mp.nstr(M3, 10)}")
        print(f"  M_4(T={T}, q={q}) = {mp.nstr(M4, 10)}")
        # Cauchy-Schwarz check: M_3^2 <= M_2 * M_4
        cs_bound = mp.sqrt(M2 * M4)
        print(f"  Cauchy-Schwarz: sqrt(M_2 M_4) = {mp.nstr(cs_bound, 10)} (>= M_3 = {mp.nstr(M3, 10)})")
        # Holder for M_3 in terms of M_2: trivial L^inf bound
        # E[|L|^3] <= sqrt(E[|L|^4] * E[|L|^2]) by C-S applied to |L|^2 . |L|
        # Equivalently M_3 <= sqrt(M_2 M_4)
        # Compare with the classical heuristic:
        # M_2 ~ phi(q) q T (log qT) / phi(q) = q T log(qT)
        # M_4 ~ phi(q) q T (log qT)^4 / phi(q)^2 = (q T (log qT)^4)/phi(q)
        # Hence M_3 ~ q T (log qT)^{5/2} (by Holder M_3 = M_2^{1/2} M_4^{1/2} heuristically)
        logqT = mp.log(q * T)
        scale_M2 = q * T * logqT
        scale_M3 = q * T * logqT**(mp.mpf('2.5'))
        scale_M4 = q * T * logqT**4
        print(f"  Heuristic scales:")
        print(f"    M_2/qT log(qT)        = {mp.nstr(M2/scale_M2, 6)}  (~ phi(q)/q ~ {mp.nstr(mp.mpf(euler_phi(int(q)))/q, 6)})")
        print(f"    M_3/(qT log(qT)^2.5)  = {mp.nstr(M3/scale_M3, 6)}")
        print(f"    M_4/(qT log(qT)^4)    = {mp.nstr(M4/scale_M4, 6)}")
        print()

if __name__ == "__main__":
    main()
