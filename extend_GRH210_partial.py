# ---------------- LDL PSD test ----------------

def ldl_psd_test(M):
    n = M.rows
    A = matrix(n, n)
    for i in range(n):
        for j in range(n):
            A[i, j] = M[i, j]
    diag_values = []
    for k in range(n):
        d_k = A[k, k]
        diag_values.append(d_k)
        if d_k <= 0:
            return False, min(diag_values), max(diag_values), k
        for i in range(k + 1, n):
            factor = A[i, k] / d_k
            for j in range(k + 1, n):
                A[i, j] = A[i, j] - factor * A[k, j]
    return True, min(diag_values), max(diag_values), n

def mu(n): return ell[n + 1]

def hankel_H(n):
    M = matrix(n + 1, n + 1)
    for i in range(n + 1):
        for j in range(n + 1):
            M[i, j] = mu(i + j)
    return M

def hankel_J(n):
    M = matrix(n + 1, n + 1)
    for i in range(n + 1):
        for j in range(n + 1):
            M[i, j] = mu(i + j + 1)
    return M

