# ---------------------------------------------------------------- cone graph (verbatim from p56_cert.py, stage D)
def cone_graph(k, Rmax):
    def vid(r, m):
        return 0 if r == 0 else 1 + k * (r - 1) * r // 2 + m
    N = 1 + k * Rmax * (Rmax + 1) // 2
    K = np.zeros((N, N)); ring = np.zeros(N, int)
    def add(a, b):
        K[a, a] += 1; K[b, b] += 1; K[a, b] -= 1; K[b, a] -= 1
    for m in range(k):
        add(0, vid(1, m))
    cut = {0: k}
    for r in range(1, Rmax + 1):
        nr = k * r
        for m in range(nr):
            ring[vid(r, m)] = r
            add(vid(r, m), vid(r, (m + 1) % nr))
        ups = 0
        for m in range(nr):
            s, j = divmod(m, r)
            tg = [s * (r + 1) + j, s * (r + 1) + j + 1] + ([s * (r + 1) - 1] if j == 0 else [])
            for tm in tg:
                ups += 1
                if r < Rmax:
                    add(vid(r, m), vid(r + 1, tm % (k * (r + 1))))
                else:
                    K[vid(r, m), vid(r, m)] += 1
        cut[r] = ups
    return K, ring, cut

def symmetry_maps(k, Rmax):
    N = 1 + k * Rmax * (Rmax + 1) // 2
    rot = np.zeros(N, int); ref = np.zeros(N, int)
    for r in range(1, Rmax + 1):
        base = 1 + k * (r - 1) * r // 2
        for m in range(k * r):
            rot[base + m] = base + (m + r) % (k * r)
            ref[base + m] = base + (-m) % (k * r)
    return rot, ref

def orbits(rot, ref):
    N = len(rot); seen = np.zeros(N, bool); orbs = []
    for v in range(N):
        if seen[v]:
            continue
        orb = {v}; stack = [v]
        while stack:
            u = stack.pop()
            for w in (rot[u], ref[u]):
                if w not in orb:
                    orb.add(w); stack.append(w)
        for u in orb:
            seen[u] = True
        orbs.append(sorted(orb))
    return orbs

def gauss_stuff(XA, PA):  # verbatim estimator of p56_cert.py (float64, with the clip)
    xe, V = np.linalg.eigh(XA)
    Xh = (V * np.sqrt(xe)) @ V.T
    Xmh = (V / np.sqrt(xe)) @ V.T
    C = Xh @ PA @ Xh; C = (C + C.T) / 2
    mu, Q = np.linalg.eigh(C)
    nu = np.maximum(np.sqrt(np.clip(mu, 0.25, None)), 0.5 + 1e-13)
    sp_ = np.log((nu + 0.5) / (nu - 0.5))
    S = float(np.sum((nu + 0.5) * np.log(nu + 0.5) - (nu - 0.5) * np.log(nu - 0.5)))
    B = Xh @ Q
    DP = (B * (sp_ / (2 * nu))) @ B.T
    return S, (DP + DP.T) / 2, float(sp_.max())

def mp_gauss(XA, PA, apex_index):
    n = XA.rows
    E, V = mp.eigsy(XA)
    Xh = V * mp.diag([mp.sqrt(E[i]) for i in range(n)]) * V.T
    C = Xh * PA * Xh
    C = (C + C.T) / 2
    mu, Q = mp.eigsy(C)
    half = mp.mpf(1) / 2
    nus = [mp.sqrt(mu[i]) for i in range(n)]
    eps = [mp.log((x + half) / (x - half)) for x in nus]
    B = Xh * Q
    b0 = 2 * mp.fsum(B[apex_index, j] ** 2 * eps[j] / (2 * nus[j]) for j in range(n))
    S = mp.fsum((x + half) * mp.log(x + half) - (x - half) * mp.log(x - half) for x in nus)
    return b0, S, max(eps)

def sector_matrices(K, orbs):
    """orbit basis restriction of K (integer sums) -> float64 and mp versions."""
    no = len(orbs)
    Ks = np.zeros((no, no)); sizes = np.array([len(o) for o in orbs])
    for i, oi in enumerate(orbs):
        sub = K[np.ix_(oi, range(K.shape[0]))]
        for j, oj in enumerate(orbs):
            Ks[i, j] = sub[:, oj].sum()
    Kf = Ks / np.sqrt(np.outer(sizes, sizes))
    Km = mp.matrix(no, no)
    for i in range(no):
        for j in range(no):
            if Ks[i, j] != 0:
                Km[i, j] = mp.mpf(int(round(Ks[i, j]))) / mp.sqrt(int(sizes[i] * sizes[j]))
    return Kf, Km

