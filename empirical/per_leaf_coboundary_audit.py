"""Leaf-restricted full-block coboundary audit for minimizing local rows.

This is the filtered follow-up to local_row_balanced_leakage.py.  For each
selected conductor leaf S, it rebuilds the local adjacency constructor and
projects the full-block C2 space, raw carry cocycle, and section-change
coboundary columns to paths whose source, middle, and target all lie in S.

The resulting residual answers a narrower but sharper question than the
support-level leakage census:

    Is the carry cochain on this leaf generated by leaf-internal full-block
    section changes?

Large leaves can be skipped by dimension limit; pass a larger --c2-limit or
--field-prime for a modular run when you intentionally want the heavier audit.
"""

