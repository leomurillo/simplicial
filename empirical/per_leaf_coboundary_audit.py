C2Key = tuple[Label, Label, str, str, str, Label, Label]
Cell = tuple[Label, ...]


def split_leaf(name: str) -> tuple[str, ...]:
    return tuple(part.strip() for part in name.split("+") if part.strip())


def path_in_leaf(key: C2Key, leaf: set[str]) -> bool:
    _left_eta, _right_eta, source, middle, target, _output, _input = key
    return source in leaf and middle in leaf and target in leaf


def generator_in_leaf(generator: SectionGenerator, leaf: set[str]) -> bool:
    return generator.source in leaf and generator.target in leaf


def safe_ratio(numerator: Any, denominator: Any) -> float | None:
    if numerator is None or denominator is None:
        return None
    denominator_int = int(denominator)
    if denominator_int == 0:
        return None
    return int(numerator) / denominator_int


def safe_float_ratio(numerator: Any, denominator: Any) -> float | None:
    if numerator is None or denominator is None:
        return None
    denominator_float = float(denominator)
    if denominator_float == 0.0:
        return None
    return float(numerator) / denominator_float


def fraction_l1_mass(vector: dict[int, Fraction]) -> Fraction:
    return sum((abs(value) for value in vector.values()), Fraction(0))


def finite_field_support_mass(vector: dict[int, int]) -> int:
    return len(vector)


def c2_volume_normalized_masses(
    raw_l1_mass: int | Fraction,
    residual_l1_mass: int | Fraction | None,
    c2_dimension: int,
) -> dict[str, float | None]:
    """Normalize carry mass by the full leaf C2 coordinate volume.

    This is the first concrete nu_lambda^E-style measure in this stack: every
    leaf-full-block C2 coordinate has mass 1 / dim(C2_leaf), and a cochain is
    measured by coefficient L1 mass over Q, or by nonzero support mass over a
    finite field where coefficient size has no canonical order.
    """

    if c2_dimension == 0:
        return {
            "nu_lambda_E_raw_mass": None,
            "nu_lambda_E_residual_mass": None,
            "nu_lambda_E_deficit": None,
        }
    raw_mass = float(raw_l1_mass) / c2_dimension
    residual_mass = (
        None
        if residual_l1_mass is None
        else float(residual_l1_mass) / c2_dimension
    )
    if raw_mass == 0.0 and residual_mass == 0.0:
        deficit = 0.0
    else:
        deficit = safe_float_ratio(residual_mass, raw_mass)
    return {
        "nu_lambda_E_raw_mass": raw_mass,
        "nu_lambda_E_residual_mass": residual_mass,
        "nu_lambda_E_deficit": deficit,
    }


def orbit_volume_normalized_masses(
    raw_orbits: int | None,
    residual_orbits: int | None,
    orbit_volume: int | None,
) -> dict[str, float | None]:
    if orbit_volume is None or orbit_volume == 0:
        return {
            "orbit_quotient_raw_mass": None,
            "orbit_quotient_residual_mass": None,
            "orbit_quotient_deficit": None,
        }
    raw_mass = None if raw_orbits is None else raw_orbits / orbit_volume
    residual_mass = None if residual_orbits is None else residual_orbits / orbit_volume
    if raw_mass == 0.0 and residual_mass == 0.0:
        deficit = 0.0
    else:
        deficit = safe_float_ratio(residual_mass, raw_mass)
    return {
        "orbit_quotient_raw_mass": raw_mass,
        "orbit_quotient_residual_mass": residual_mass,
        "orbit_quotient_deficit": deficit,
    }


def load_support_leaf_stats(path: Path) -> dict[tuple[str, str], dict[str, Any]]:
    if not path.exists():
        return {}
    payload = json.loads(path.read_text(encoding="utf-8"))
    index: dict[tuple[str, str], dict[str, Any]] = {}
    for row in payload.get("rows", []):
        ring = row.get("ring")
        for leaf in row.get("leaves", []):
            if ring and leaf.get("leaf"):
                index[(str(ring), str(leaf["leaf"]))] = leaf
    return index


def normalized_residual_metrics(
    row: dict[str, Any],
    support_leaf: dict[str, Any] | None,
) -> dict[str, Any]:
    raw_support = row.get("raw_support", row.get("raw_support_before_indexing"))
    residual_support = row.get("residual_support")
    active_atom_mass = None
    active_orbit_count = None
    active_mass_fraction = None
    support_leakage_fraction = None
    balanced_leakage = None
    if support_leaf:
        active_atom_mass = support_leaf.get("active_atom_mass")
        active_orbit_count = support_leaf.get("active_orbits")
        active_mass_fraction = support_leaf.get("active_mass_fraction")
        support_leakage_fraction = support_leaf.get("support_leakage_fraction")
        balanced_leakage = support_leaf.get("balanced_leakage")

    if active_atom_mass is None:
        active_atom_mass = raw_support

    packet_mass_normalized = safe_ratio(residual_support, active_atom_mass)
    metrics = {
        "active_atom_mass": active_atom_mass,
        "active_orbit_count": active_orbit_count,
        "active_mass_fraction": active_mass_fraction,
        "support_leakage_fraction": support_leakage_fraction,
        "balanced_leakage": balanced_leakage,
        "orbit_count_normalized_residual": safe_ratio(residual_support, active_orbit_count),
        "packet_mass_normalized_residual": packet_mass_normalized,
        "nu_lambda_E_normalized_carry_proxy": row.get("nu_lambda_E_residual_mass"),
        "nu_lambda_E_normalization": (
            "C2-volume measure: coefficient L1 mass over Q, or nonzero support "
            "mass over a finite field, divided by the leaf full-block C2 dimension"
        ),
    }
    return metrics


def leaf_pair_keys(reducer: CocycleReducer, leaf: set[str]) -> list[tuple[Label, Label, str, str, str]]:
    pair_keys = []
    for left, right in reducer.composable_pairs:
        pair_key = (left.eta, right.eta, right.source, right.target, left.target)
        if right.source in leaf and right.target in leaf and left.target in leaf:
            pair_keys.append(pair_key)
    pair_keys.sort(key=reducer.pair_sort_key)
    return pair_keys


def leaf_c2_indexer(
    reducer: CocycleReducer,
    leaf: set[str],
) -> tuple[int, Callable[[C2Key], int | None], int]:
    constructor = reducer.constructor
    pair_keys = leaf_pair_keys(reducer, leaf)

    offsets: dict[
        tuple[Label, Label, str, str, str],
        tuple[int, dict[Label, int], dict[Label, int], int],
    ] = {}
    offset = 0
    for pair_key in pair_keys:
        _left_eta, _right_eta, source, _middle, target = pair_key
        outputs = constructor.packets[target]
        inputs = constructor.packets[source]
        output_indexes = {label: index for index, label in enumerate(outputs)}
        input_indexes = {label: index for index, label in enumerate(inputs)}
        offsets[pair_key] = (offset, output_indexes, input_indexes, len(inputs))
        offset += len(outputs) * len(inputs)

    def indexer(key: C2Key) -> int | None:
        item = offsets.get(key[:5])
        if item is None:
            return None
        base, output_indexes, input_indexes, input_count = item
        output = key[5]
        input_label = key[6]
        return base + output_indexes[output] * input_count + input_indexes[input_label]

    return offset, indexer, len(pair_keys)


def leaf_c2_keys(reducer: CocycleReducer, leaf: set[str]) -> list[C2Key]:
    constructor = reducer.constructor
    keys: list[C2Key] = []
    for left_eta, right_eta, source, middle, target in leaf_pair_keys(reducer, leaf):
        for output in constructor.packets[target]:
            for input_label in constructor.packets[source]:
                keys.append((left_eta, right_eta, source, middle, target, output, input_label))
    return keys


def transform_c2_key(reducer: CocycleReducer, key: C2Key, action: Any) -> C2Key:
    left_eta, right_eta, source, middle, target, output, input_label = key
    ring = reducer.ring
    return (
        ring.apply(action, left_eta),
        ring.apply(action, right_eta),
        source,
        middle,
        target,
        ring.apply(action, output),
        ring.apply(action, input_label),
    )


def canonical_c2_key(reducer: CocycleReducer, key: C2Key) -> C2Key:
    return min(
        (transform_c2_key(reducer, key, action) for action in reducer.ring.normalizer_actions),
        key=reducer.c2_sort_key,
    )


def c2_orbit_volume_burnside(
    reducer: CocycleReducer,
    leaf: set[str],
    pair_keys: list[tuple[Label, Label, str, str, str]],
) -> int:
    """Count leaf C2 orbits by Burnside without canonicalizing every coordinate."""

    constructor = reducer.constructor
    fixed_sum = 0
    for action in reducer.ring.normalizer_actions:
        fixed_by_packet = {
            packet: sum(
                1 for label in labels if reducer.ring.apply(action, label) == label
            )
            for packet, labels in constructor.packets.items()
            if packet in leaf
        }
        fixed_eta_pairs = 0
        for left_eta, right_eta, source, _middle, target in pair_keys:
            if reducer.ring.apply(action, left_eta) != left_eta:
                continue
            if reducer.ring.apply(action, right_eta) != right_eta:
                continue
            fixed_eta_pairs += fixed_by_packet[target] * fixed_by_packet[source]
        fixed_sum += fixed_eta_pairs

    gamma_size = len(reducer.ring.normalizer_actions)
    if fixed_sum % gamma_size != 0:
        raise ValueError("Burnside C2 quotient volume was nonintegral")
    return fixed_sum // gamma_size


def c2_orbit_quotient(
    reducer: CocycleReducer,
    leaf: set[str],
    *,
    orbit_quotient_limit: int,
) -> tuple[dict[str, Any], list[C2Key] | None]:
    pair_keys = leaf_pair_keys(reducer, leaf)
    c2_dimension = 0
    for _left_eta, _right_eta, source, _middle, target in pair_keys:
        c2_dimension += (
            len(reducer.constructor.packets[target])
            * len(reducer.constructor.packets[source])
        )

    volume = c2_orbit_volume_burnside(reducer, leaf, pair_keys)
    keys_by_index = None
    support_indexed = c2_dimension <= orbit_quotient_limit
    if support_indexed:
        keys_by_index = leaf_c2_keys(reducer, leaf)

    return (
        {
            "c2_orbit_quotient_skipped": False,
            "c2_orbit_quotient_method": "burnside",
            "c2_orbit_support_indexed": support_indexed,
            "c2_orbit_support_index_limit": orbit_quotient_limit,
            "c2_orbit_support_index_reason": (
                None
                if support_indexed
                else "c2_dimension exceeds orbit support indexing limit"
            ),
            "c2_orbit_quotient_volume": volume,
            "c2_orbit_average_size": safe_float_ratio(c2_dimension, volume),
        },
        keys_by_index,
    )


def orbit_support_count(
    reducer: CocycleReducer,
    vector: dict[int, Any],
    c2_keys_by_index: list[C2Key] | None,
) -> int | None:
    if c2_keys_by_index is None:
        return None
    return len({canonical_c2_key(reducer, c2_keys_by_index[index]) for index in vector})


def labels_in_leaf(constructor: LocalAdjacencyConstructor, leaf: set[str]) -> tuple[Label, ...]:
    labels: list[Label] = []
    for packet in sorted(leaf):
        labels.extend(constructor.packets.get(packet, ()))
    return tuple(labels)


def leaf_closed_cells(
    constructor: LocalAdjacencyConstructor,
    leaf: set[str],
    arity: int,
    *,
    max_prefixes: int,
) -> tuple[Cell, ...] | None:
    labels = labels_in_leaf(constructor, leaf)
    prefix_count = len(labels) ** (arity - 1)
    if prefix_count > max_prefixes:
        return None
    label_set = set(labels)
    cells: list[Cell] = []
    for prefix in product(labels, repeat=arity - 1):
        final = constructor.ring.add_many(prefix)
        if final != constructor.ring.zero and final in label_set:
            cells.append(tuple(prefix) + (final,))
    return tuple(cells)


def leaf_cell_orbit_summary(
    constructor: LocalAdjacencyConstructor,
    leaf: set[str],
    arity: int,
    *,
    max_prefixes: int,
) -> tuple[dict[str, Any], dict[Cell, int] | None]:
    cells = leaf_closed_cells(constructor, leaf, arity, max_prefixes=max_prefixes)
    prefix_count = len(labels_in_leaf(constructor, leaf)) ** (arity - 1)
    if cells is None:
        return (
            {
                f"h{arity}_leaf_prefix_count": prefix_count,
                f"h{arity}_leaf_cell_dimension": None,
                f"h{arity}_leaf_orbit_quotient_dimension": None,
                f"h{arity}_leaf_skipped": True,
                f"h{arity}_leaf_reason": "prefix count exceeds hyper-adjacency limit",
            },
            None,
        )
    orbits = constructor.tuple_orbits(cells)
    cell_to_orbit: dict[Cell, int] = {}
    family_counts: Counter[str] = Counter()
    for orbit_id, orbit in enumerate(orbits):
        seed = min(orbit, key=constructor.tuple_name)
        family_counts[str(constructor.conductor_family(seed))] += 1
        for cell in orbit:
            cell_to_orbit[cell] = orbit_id
    return (
        {
            f"h{arity}_leaf_prefix_count": prefix_count,
            f"h{arity}_leaf_cell_dimension": len(cells),
            f"h{arity}_leaf_orbit_quotient_dimension": len(orbits),
            f"h{arity}_leaf_family_orbit_counts": dict(sorted(family_counts.items())),
            f"h{arity}_leaf_skipped": False,
        },
        cell_to_orbit,
    )


def leaf_hyper_adjacency_summary(
    constructor: LocalAdjacencyConstructor,
    leaf: set[str],
    *,
    max_prefixes: int,
) -> dict[str, Any]:
    h3, h3_orbits = leaf_cell_orbit_summary(constructor, leaf, 3, max_prefixes=max_prefixes)
    h4, h4_orbits = leaf_cell_orbit_summary(constructor, leaf, 4, max_prefixes=max_prefixes)
    summary: dict[str, Any] = {
        **h3,
        **h4,
        "hyper_adjacency_quotient_status": (
            "support orbit dimensions only; full current quotient rank not computed"
        ),
    }
    if h3_orbits is None or h4_orbits is None:
        summary.update(
            {
                "h4_to_h3_target_orbits_hit": None,
                "h4_to_h3_orbit_cokernel_dimension": None,
            }
        )
        return summary

    h4_cells = tuple(h4_orbits)
    target_hit: set[int] = set()
    valid = 0
    invalid = 0
    for cell in h4_cells:
        for pair in combinations(range(4), 2):
            merged = constructor.ring.add(cell[pair[0]], cell[pair[1]])
            if merged == constructor.ring.zero:
                invalid += 1
                continue
            contracted = tuple([merged] + [cell[index] for index in range(4) if index not in pair])
            target = h3_orbits.get(contracted)
            if target is None:
                invalid += 1
                continue
            valid += 1
            target_hit.add(target)

    target_dim = int(h3["h3_leaf_orbit_quotient_dimension"])
    summary.update(
        {
            "h4_to_h3_valid_contractions": valid,
            "h4_to_h3_invalid_contractions": invalid,
            "h4_to_h3_target_orbits_hit": len(target_hit),
            "h4_to_h3_orbit_cokernel_dimension": target_dim - len(target_hit),
            "h4_to_h3_quotient_status": (
                "support contraction orbit cokernel; not full H_hyp current quotient"
            ),
        }
    )
    return summary


def reduce_mod(
    reducer: CocycleReducer,
    generators: tuple[SectionGenerator, ...],
    c2_index: Callable[[C2Key], int | None],
    raw_keys: dict[C2Key, Fraction],
    c2_dimension: int,
    c2_keys_by_index: list[C2Key] | None,
    c2_orbit_volume: int | None,
    modulus: int,
) -> dict[str, Any]:
    basis: dict[int, dict[int, int]] = {}
    for generator in generators:
        column: dict[int, int] = {}
        for key, value in reducer.coboundary_column(generator).items():
            index = c2_index(key)
            if index is None:
                continue
            entry = int(value) % modulus
            if entry:
                column[index] = (column.get(index, 0) + entry) % modulus
                if not column[index]:
                    del column[index]
        reduced = reducer._reduce_vector_mod(column, basis, modulus)
        if not reduced:
            continue
        pivot = min(reduced)
        inverse = pow(reduced[pivot], -1, modulus)
        basis[pivot] = {
            index: (value * inverse) % modulus
            for index, value in reduced.items()
            if (value * inverse) % modulus
        }

    raw: dict[int, int] = {}
    for key, value in raw_keys.items():
        index = c2_index(key)
        if index is None:
            continue
        entry = int(value) % modulus
        if entry:
            raw[index] = (raw.get(index, 0) + entry) % modulus
            if not raw[index]:
                del raw[index]
    residual = reducer._reduce_vector_mod(raw, basis, modulus)
    raw_orbits = orbit_support_count(reducer, raw, c2_keys_by_index)
    residual_orbits = orbit_support_count(reducer, residual, c2_keys_by_index)
    masses = c2_volume_normalized_masses(
        finite_field_support_mass(raw),
        finite_field_support_mass(residual),
        c2_dimension,
    )
    return {
        "coefficient_field": f"F_{modulus}",
        "nu_lambda_E_field_mode": "finite_field_support_mass",
        "coboundary_rank": len(basis),
        "raw_support": len(raw),
        "residual_support": len(residual),
        "raw_orbit_quotient_support": raw_orbits,
        "residual_orbit_quotient_support": residual_orbits,
        **orbit_volume_normalized_masses(raw_orbits, residual_orbits, c2_orbit_volume),
        **masses,
        "residual_equal_raw": residual == raw,
        "raw_is_coboundary": len(residual) == 0,
    }


def reduce_q(
    reducer: CocycleReducer,
    generators: tuple[SectionGenerator, ...],
    c2_index: Callable[[C2Key], int | None],
    raw_keys: dict[C2Key, Fraction],
    c2_dimension: int,
    c2_keys_by_index: list[C2Key] | None,
    c2_orbit_volume: int | None,
) -> dict[str, Any]:
    basis: dict[int, dict[int, Fraction]] = {}
    for generator in generators:
        column: dict[int, Fraction] = {}
        for key, value in reducer.coboundary_column(generator).items():
            index = c2_index(key)
            if index is None:
                continue
            column[index] = column.get(index, Fraction(0)) + value
            if not column[index]:
                del column[index]
        reduced = reducer._reduce_vector(column, basis)
        if not reduced:
            continue
        pivot = min(reduced)
        pivot_value = reduced[pivot]
        basis[pivot] = {index: value / pivot_value for index, value in reduced.items()}

    raw: dict[int, Fraction] = {}
    for key, value in raw_keys.items():
        index = c2_index(key)
        if index is None:
            continue
        raw[index] = raw.get(index, Fraction(0)) + value
        if not raw[index]:
            del raw[index]
    residual = reducer._reduce_vector(raw, basis)
    raw_orbits = orbit_support_count(reducer, raw, c2_keys_by_index)
    residual_orbits = orbit_support_count(reducer, residual, c2_keys_by_index)
    masses = c2_volume_normalized_masses(
        fraction_l1_mass(raw),
        fraction_l1_mass(residual),
        c2_dimension,
    )
    return {
        "coefficient_field": "Q",
        "nu_lambda_E_field_mode": "coefficient_l1_mass",
        "coboundary_rank": len(basis),
        "raw_support": len(raw),
        "residual_support": len(residual),
        "raw_orbit_quotient_support": raw_orbits,
        "residual_orbit_quotient_support": residual_orbits,
        **orbit_volume_normalized_masses(raw_orbits, residual_orbits, c2_orbit_volume),
        **masses,
        "residual_equal_raw": residual == raw,
        "raw_is_coboundary": len(residual) == 0,
    }


def audit_leaf(
    ring_name: str,
    leaf_name: str,
    *,
    c2_limit: int,
    field_prime: int | None,
    support_leaf: dict[str, Any] | None,
    orbit_quotient_limit: int,
    hyper_prefix_limit: int,
) -> dict[str, Any]:
    started = perf_counter()
    factory = RING_FACTORIES[ring_name]
    reducer = CocycleReducer(LocalAdjacencyConstructor(factory()))
    constructor = reducer.constructor
    leaf = set(split_leaf(leaf_name))
    c2_dimension, c2_index, pair_count = leaf_c2_indexer(reducer, leaf)
    orbit_summary, c2_keys_by_index = c2_orbit_quotient(
        reducer,
        leaf,
        orbit_quotient_limit=orbit_quotient_limit,
    )
    c2_orbit_volume = orbit_summary.get("c2_orbit_quotient_volume")
    hyper_summary = leaf_hyper_adjacency_summary(
        constructor,
        leaf,
        max_prefixes=hyper_prefix_limit,
    )
    generators = tuple(
        generator
        for generator in reducer.section_generators("full_block")
        if generator_in_leaf(generator, leaf)
    )
    raw_vector = {
        key: value
        for key, value in reducer.raw_vector().items()
        if path_in_leaf(key, leaf)
    }

    base = {
        "ring": ring_name,
        "leaf": leaf_name,
        "packets": sorted(leaf),
        "mode": "leaf_full_block",
        "c2_scope": "leaf_full_block",
        "c2_dimension": c2_dimension,
        "leaf_pair_count": pair_count,
        "c1_generators": len(generators),
        "raw_support_before_indexing": len(raw_vector),
        "raw_support": len(raw_vector),
        **orbit_summary,
        **hyper_summary,
        **c2_volume_normalized_masses(
            sum((abs(value) for value in raw_vector.values()), Fraction(0)),
            None,
            c2_dimension,
        ),
    }
    if c2_dimension > c2_limit:
        row = {
            **base,
            "skipped": True,
            "reason": "c2_dimension exceeds limit",
            "c2_limit": c2_limit,
            "elapsed_seconds": round(perf_counter() - started, 3),
        }
        return {**row, **normalized_residual_metrics(row, support_leaf)}

    if field_prime is not None:
        reduced = reduce_mod(
            reducer,
            generators,
            c2_index,
            raw_vector,
            c2_dimension,
            c2_keys_by_index,
            int(c2_orbit_volume) if c2_orbit_volume is not None else None,
            field_prime,
        )
    else:
        reduced = reduce_q(
            reducer,
            generators,
            c2_index,
            raw_vector,
            c2_dimension,
            c2_keys_by_index,
            int(c2_orbit_volume) if c2_orbit_volume is not None else None,
        )
    row = {
        **base,
        **reduced,
        "residual_dimension": c2_dimension - int(reduced["coboundary_rank"]),
        "residual_deficit": (
            0.0
            if int(reduced["raw_support"]) == 0
            else int(reduced["residual_support"]) / int(reduced["raw_support"])
        ),
        "skipped": False,
        "elapsed_seconds": round(perf_counter() - started, 3),
    }
    return {**row, **normalized_residual_metrics(row, support_leaf)}


def selected_from_balanced_report(path: Path) -> list[tuple[str, str]]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    selected: list[tuple[str, str]] = []
    for row in payload["rows"]:
        ring = row["ring"]
        leaf = row.get("best_proper_regular_leaf") or row.get("best_regular_leaf")
        if ring in RING_FACTORIES and leaf:
            selected.append((ring, leaf))
    return selected


def json_ready(obj: Any) -> Any:
    if isinstance(obj, float):
        return round(obj, 12)
    if isinstance(obj, list):
        return [json_ready(item) for item in obj]
    if isinstance(obj, dict):
        return {str(key): json_ready(value) for key, value in obj.items()}
    return obj


def fmt(value: Any) -> str:
    if value is None:
        return "n/a"
    if isinstance(value, float):
        return f"{value:.6f}"
    return str(value)


def make_report(rows: list[dict[str, Any]], output_json: Path) -> str:
    lines = [
        "# Per-Leaf Full-Block Coboundary Audit",
        "",
        "## Status",
        "",
        f"- JSON artifact: `{output_json}`",
        "- C2 scope: full block restricted to source/middle/target inside the conductor leaf",
        "- C1 generators: full-block section changes with source/target inside the conductor leaf",
        "- normalized residual columns use the support-atlas active orbit count and active atom mass when available, falling back to raw support for atom mass",
        "- `nu_lambda^E` uses coefficient L1 mass over Q, or nonzero support mass over a finite field, divided by the leaf full-block C2 dimension",
        "- C2 orbit quotient columns use normalizer orbits on the leaf full-block C2 coordinates",
        "- H4->H3 cokernel is a support-level orbit cokernel, not the full current quotient `H_hyp`",
        "",
        "This is the first filtered residual audit on the minimizing local leaves. Skipped rows need a larger dimension limit or a modular run.",
        "",
        "| ring | leaf | field | C2 dim | C1 gens | raw support | residual support | residual deficit | res/atom | nu_E residual | C2 orbit vol | residual orbit support | orbit residual mass | H3 orbits | H4 orbits | H4->H3 cokernel | residual dim | status | seconds |",
        "|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|---:|",
    ]
    for row in rows:
        status = "skipped" if row.get("skipped") else ("closed" if row.get("raw_is_coboundary") else "residual")
        lines.append(
            f"| {row['ring']} | `{row['leaf']}` | {row.get('coefficient_field', 'n/a')} | "
            f"{row['c2_dimension']} | {row['c1_generators']} | "
            f"{row.get('raw_support', row.get('raw_support_before_indexing', 'n/a'))} | "
            f"{row.get('residual_support', 'n/a')} | {fmt(row.get('residual_deficit'))} | "
            f"{fmt(row.get('packet_mass_normalized_residual'))} | "
            f"{fmt(row.get('nu_lambda_E_residual_mass'))} | "
            f"{fmt(row.get('c2_orbit_quotient_volume'))} | "
            f"{fmt(row.get('residual_orbit_quotient_support'))} | "
            f"{fmt(row.get('orbit_quotient_residual_mass'))} | "
            f"{fmt(row.get('h3_leaf_orbit_quotient_dimension'))} | "
            f"{fmt(row.get('h4_leaf_orbit_quotient_dimension'))} | "
            f"{fmt(row.get('h4_to_h3_orbit_cokernel_dimension'))} | "
            f"{row.get('residual_dimension', 'n/a')} | {status} | {fmt(row.get('elapsed_seconds'))} |"
        )
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--leaf",
        action="append",
        default=None,
        help="Leaf spec 'ring|leaf', e.g. 'F_4[u]/(u^2)|u^2'. May repeat.",
    )
    parser.add_argument("--leaf-source", type=Path, default=DEFAULT_LEAF_SOURCE)
    parser.add_argument("--c2-limit", type=int, default=1_000_000)
    parser.add_argument("--orbit-quotient-limit", type=int, default=1_000_000)
    parser.add_argument("--hyper-prefix-limit", type=int, default=500_000)
    parser.add_argument("--field-prime", type=int, default=None)
    parser.add_argument("--report", type=Path, default=REPORTS / "per_leaf_coboundary_audit.md")
    parser.add_argument("--json", type=Path, default=REPORTS / "per_leaf_coboundary_audit.json")
    args = parser.parse_args()

    if args.leaf:
        selected = []
        for spec in args.leaf:
            if "|" not in spec:
                raise SystemExit("--leaf must be formatted as 'ring|leaf'")
            ring, leaf = spec.split("|", 1)
            selected.append((ring.strip(), leaf.strip()))
    else:
        selected = selected_from_balanced_report(args.leaf_source)
    support_leaf_stats = load_support_leaf_stats(args.leaf_source)

    rows = [
        audit_leaf(
            ring,
            leaf,
            c2_limit=args.c2_limit,
            field_prime=args.field_prime,
            support_leaf=support_leaf_stats.get((ring, leaf)),
            orbit_quotient_limit=args.orbit_quotient_limit,
            hyper_prefix_limit=args.hyper_prefix_limit,
        )
        for ring, leaf in selected
    ]

    args.json.parent.mkdir(parents=True, exist_ok=True)
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.json.write_text(json.dumps(json_ready({"rows": rows}), indent=2), encoding="utf-8")
    args.report.write_text(make_report(rows, args.json), encoding="utf-8")
    print(f"Wrote {args.report}")
    print(f"Wrote {args.json}")
    print(
        json.dumps(
            json_ready(
                {
                    f"{row['ring']}|{row['leaf']}": {
                        "skipped": row.get("skipped", False),
                        "raw_support": row.get("raw_support"),
                        "residual_support": row.get("residual_support"),
                        "residual_deficit": row.get("residual_deficit"),
                        "packet_mass_normalized_residual": row.get("packet_mass_normalized_residual"),
                        "orbit_count_normalized_residual": row.get("orbit_count_normalized_residual"),
                        "nu_lambda_E_raw_mass": row.get("nu_lambda_E_raw_mass"),
                        "nu_lambda_E_residual_mass": row.get("nu_lambda_E_residual_mass"),
                        "nu_lambda_E_deficit": row.get("nu_lambda_E_deficit"),
                        "c2_orbit_quotient_volume": row.get("c2_orbit_quotient_volume"),
                        "residual_orbit_quotient_support": row.get("residual_orbit_quotient_support"),
                        "orbit_quotient_residual_mass": row.get("orbit_quotient_residual_mass"),
                        "h3_leaf_orbit_quotient_dimension": row.get("h3_leaf_orbit_quotient_dimension"),
                        "h4_leaf_orbit_quotient_dimension": row.get("h4_leaf_orbit_quotient_dimension"),
                        "h4_to_h3_orbit_cokernel_dimension": row.get("h4_to_h3_orbit_cokernel_dimension"),
                    }
                    for row in rows
                }
            ),
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
