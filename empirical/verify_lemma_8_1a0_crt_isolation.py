# ---- exact dense linear algebra over Fraction, group basis on Z/m -------------------

def zeros(m):
    return [[Fraction(0)] * m for _ in range(m)]


def ident(m):
    M = zeros(m)
    for i in range(m):
        M[i][i] = Fraction(1)
    return M


def matmul(A, B, m):
    C = zeros(m)
    for i in range(m):
        Ai, Ci = A[i], C[i]
        for k in range(m):
            a = Ai[k]
            if a:
                Bk = B[k]
                for j in range(m):
                    Ci[j] += a * Bk[j]
    return C


def matadd(A, B, m):
    return [[A[i][j] + B[i][j] for j in range(m)] for i in range(m)]


def matsub(A, B, m):
    return [[A[i][j] - B[i][j] for j in range(m)] for i in range(m)]


def scal(c, A, m):
    return [[c * A[i][j] for j in range(m)] for i in range(m)]


def equal(A, B, m):
    return all(A[i][j] == B[i][j] for i in range(m) for j in range(m))


def is_zero(A, m):
    return all(A[i][j] == 0 for i in range(m) for j in range(m))


def trace(A, m):
    return sum(A[i][i] for i in range(m))


def subgroup(m, gens):
    """Subgroup of (Z/m, +) generated by gens, by additive closure."""
    S = {0}
    frontier = [0]
    while frontier:
        x = frontier.pop()
        for g in gens:
            y = (x + g) % m
            if y not in S:
                S.add(y)
                frontier.append(y)
    return S


def avg_over(m, elems):
    """Projector (1/|H|) sum_{h in H} T_h, T_h the translation (T_h f)(x) = f(x-h)."""
    H = list(elems)
    c = Fraction(1, len(H))
    M = zeros(m)
    for x in range(m):
        row = M[x]
        for h in H:
            row[(x - h) % m] += c
    return M


# ---- elementary number theory ------------------------------------------------------

def divisors(n):
    return [d for d in range(1, n + 1) if n % d == 0]


def factorize(n):
    f, d = {}, 2
    while d * d <= n:
        while n % d == 0:
            f[d] = f.get(d, 0) + 1
            n //= d
        d += 1
    if n > 1:
        f[n] = f.get(n, 0) + 1
    return f


def mobius(n):
    if n == 1:
        return 1
    f = factorize(n)
    if any(e > 1 for e in f.values()):
        return 0
    return -1 if len(f) % 2 else 1


def phi(n):
    r = n
    for p in factorize(n):
        r -= r // p
    return r


def vp(n, p):
    v = 0
    while n % p == 0:
        v += 1
        n //= p
    return v


