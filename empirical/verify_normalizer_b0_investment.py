"""Exact verifier for B3 normalizer-saturated B0 investment.

B2 buys the minimum generated subgroup needed for prediction closure.  B3 buys
the minimum normalizer-invariant subgroup: the subgroup generated by the
normalizer orbit of the active reciprocal support.

This separates minimal information investment from symmetry-complete modeling.
"""

from __future__ import annotations

import argparse
import itertools
import json
import sys
from pathlib import Path
from typing import Any, Hashable


sys.path.insert(0, str(Path(__file__).resolve().parent))

from information_investment_functional import (
    FiniteRow,
    build_rows,
    generated_subgroup,
    normalizer_saturation,
)


Mode = Hashable
DEFAULT_JSON = Path("empirical/reports/normalizer_b0_investment.json")
DEFAULT_REPORT = Path("empirical/reports/normalizer_b0_investment.md")


def all_supports(row: FiniteRow, max_support_size: int | None) -> list[set[Mode]]:
    supports: list[set[Mode]] = []
    nonzero = list(row.nonzero_modes)
    largest = len(nonzero) if max_support_size is None else min(max_support_size, len(nonzero))
    for size in range(1, largest + 1):
        for combo in itertools.combinations(nonzero, size):
            supports.append(set(combo))
    return supports


def is_additively_closed(row: FiniteRow, support: set[Mode]) -> bool:
    with_zero = set(support)
    with_zero.add(row.zero)
    for left in with_zero:
        for right in with_zero:
            if row.add(left, right) not in with_zero:
                return False
    return True


def is_normalizer_invariant(row: FiniteRow, support: set[Mode]) -> bool:
    with_zero = set(support)
    with_zero.add(row.zero)
    for action in row.normalizer_actions:
        for label in with_zero:
            if action[label] not in with_zero:
                return False
    return True


def format_support(row: FiniteRow, support: set[Mode], max_items: int = 8) -> list[str]:
    labels = sorted(support, key=row.label_name)
    out = [row.label_name(label) for label in labels[:max_items]]
    if len(labels) > max_items:
        out.append(f"...(+{len(labels) - max_items})")
    return out


def first_overbuy(row: FiniteRow, supports: list[set[Mode]]) -> dict[str, Any] | None:
    for support in supports:
        minimal = generated_subgroup(row, support)
        saturated = normalizer_saturation(row, support)
        if len(saturated) > len(minimal):
            return {
                "support": format_support(row, support),
                "minimal_size": len(minimal),
                "normalizer_size": len(saturated),
                "minimal": format_support(row, minimal),
                "normalizer_extra": format_support(row, saturated - minimal),
            }
    return None


def verify_row(row: FiniteRow, max_support_size: int | None) -> dict[str, Any]:
    supports = all_supports(row, max_support_size)
    overbuy_count = 0
    equal_count = 0
    minimal_resources: list[float] = []
    normalizer_resources: list[float] = []
    nonzero_count = len(row.nonzero_modes)

    for support in supports:
        minimal = generated_subgroup(row, support)
        saturated = normalizer_saturation(row, support)
        if not support <= minimal:
            raise AssertionError(f"{row.key}: minimal support misses active support")
        if not minimal <= saturated:
            raise AssertionError(f"{row.key}: normalizer support misses minimal support")
        if not is_additively_closed(row, minimal):
            raise AssertionError(f"{row.key}: minimal support is not additively closed")
        if not is_additively_closed(row, saturated):
            raise AssertionError(f"{row.key}: normalizer support is not additively closed")
        if not is_normalizer_invariant(row, saturated):
            raise AssertionError(f"{row.key}: normalizer support is not invariant")
        if normalizer_saturation(row, saturated) != saturated:
            raise AssertionError(f"{row.key}: normalizer support is not idempotent")

        if len(saturated) > len(minimal):
            overbuy_count += 1
        else:
            equal_count += 1
        minimal_resources.append(len(minimal) / nonzero_count)
        normalizer_resources.append(len(saturated) / nonzero_count)

    return {
        "key": row.key,
        "row": row.name,
        "label_count": len(row.labels),
        "nonzero_count": nonzero_count,
        "normalizer_action_count": len(row.normalizer_actions),
        "support_checks": len(supports),
        "equal_count": equal_count,
        "overbuy_count": overbuy_count,
        "mean_minimal_resource": sum(minimal_resources) / len(minimal_resources),
        "mean_normalizer_resource": sum(normalizer_resources) / len(normalizer_resources),
        "mean_symmetry_premium": (
            sum(normalizer_resources) - sum(minimal_resources)
        ) / len(minimal_resources),
        "first_overbuy": first_overbuy(row, supports),
    }


def build_payload(args: argparse.Namespace) -> dict[str, Any]:
    row_keys = [key.strip() for key in args.rows.split(",") if key.strip()]
    rows = [verify_row(row, args.max_support_size) for row in build_rows(row_keys)]
    return {
        "theorem": (
            "For a finite character group G with normalizer action Gamma, "
            "the B3 symmetry-complete support of reciprocal support S is "
            "<Gamma.S>\\{0}.  It is the unique minimum-resource support that "
            "is additively closed, contains S, and is Gamma-invariant."
        ),
        "reading": (
            "B2 is minimal prediction investment.  B3 is symmetry-complete "
            "investment.  The difference is a measurable symmetry premium."
        ),
        "config": {
            "rows": row_keys,
            "max_support_size": args.max_support_size,
        },
        "rows": rows,
    }


def write_json(payload: dict[str, Any], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")


def render_overbuy(example: dict[str, Any] | None) -> str:
    if example is None:
        return "none"
    return (
        f"{', '.join(example['support'])} -> "
        f"{example['minimal_size']} vs {example['normalizer_size']}"
    )


def render_markdown(payload: dict[str, Any]) -> str:
    lines = [
        "# B3 Normalizer-Saturated Information Investment",
        "",
        "## Theorem",
        "",
        payload["theorem"],
        "",
        "## Reading",
        "",
        payload["reading"],
        "",
        "## Certified Rows",
        "",
        "| row | actions | support checks | equal | overbuy | mean minimal | mean normalizer | symmetry premium | first overbuy |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---|",
    ]
    for row in payload["rows"]:
        lines.append(
            "| {row} | {actions} | {checks} | {equal} | {overbuy} | {minimal:.6f} | "
            "{normalizer:.6f} | {premium:.6f} | {first} |".format(
                row=row["row"],
                actions=row["normalizer_action_count"],
                checks=row["support_checks"],
                equal=row["equal_count"],
                overbuy=row["overbuy_count"],
                minimal=row["mean_minimal_resource"],
                normalizer=row["mean_normalizer_resource"],
                premium=row["mean_symmetry_premium"],
                first=render_overbuy(row["first_overbuy"]),
            )
        )
    return "\n".join(lines) + "\n"


def write_report(payload: dict[str, Any], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_markdown(payload), encoding="utf-8")


def check_payload(payload: dict[str, Any], path: Path) -> None:
    recorded = json.loads(path.read_text(encoding="utf-8"))
    if recorded != payload:
        raise AssertionError(f"payload differs from {path}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--rows", default="c7,c8,c12,f4-u2,f2-u4")
    parser.add_argument(
        "--max-support-size",
        type=int,
        default=None,
        help="optional maximum active support size to enumerate",
    )
    parser.add_argument("--json", type=Path, default=DEFAULT_JSON)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    parser.add_argument("--check", type=Path, default=None)
    args = parser.parse_args()

    payload = build_payload(args)
    if args.check is not None:
        check_payload(payload, args.check)
        print(f"checked {args.check}")
        return

    write_json(payload, args.json)
    write_report(payload, args.report)
    print(f"wrote {args.report}")
    print(f"wrote {args.json}")


if __name__ == "__main__":
    main()
