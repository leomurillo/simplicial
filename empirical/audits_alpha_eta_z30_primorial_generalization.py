# Section B.  Conductor lattice on Z/N
# ----------------------------------------------------------------------------
def conductor(k: int, N: int) -> int:
    """c(k) = N / gcd(k, N).  Returns 0 by convention only if k == 0 and N == 1."""
    if k == 0:
        return 1
    return N // gcd(k, N)


def euler_phi(d: int) -> int:
    if d == 1:
        return 1
    result = d
    p = 2
    temp = d
    while p * p <= temp:
        if temp % p == 0:
            while temp % p == 0:
                temp //= p
            result -= result // p
        p += 1
    if temp > 1:
        result -= result // temp
    return result


def prime_factors(d: int) -> set[int]:
    """Distinct prime factors of d.  Returns empty set for d == 1."""
    facs = set()
    temp = d
    p = 2
    while p * p <= temp:
        while temp % p == 0:
            facs.add(p)
            temp //= p
        p += 1
    if temp > 1:
        facs.add(temp)
    return facs


def is_single_prime(d: int) -> bool:
    """True if d has exactly one distinct prime factor (incl. prime powers).
    On squarefree N, this is just 'd is a prime divisor of N'."""
    return d != 1 and len(prime_factors(d)) == 1


def build_packets(N: int) -> dict[int, list[int]]:
    pk: dict[int, list[int]] = {}
    for k in range(N):
        d = conductor(k, N)
        pk.setdefault(d, []).append(k)
    return pk


def vm_partition(N: int, packets: dict[int, list[int]]):
    """V = union of single-prime conductor packets.  M = union of cross-prime."""
    V_idx: list[int] = []
    M_idx: list[int] = []
    trivial_idx: list[int] = []
    for d, ks in packets.items():
        if d == 1:
            trivial_idx.extend(ks)
        elif is_single_prime(d):
            V_idx.extend(ks)
        else:
            M_idx.extend(ks)
    return sorted(V_idx), sorted(M_idx), sorted(trivial_idx)


def print_packet_table(N: int, packets: dict[int, list[int]]) -> None:
    print(f"  Conductor packets of Z/{N}Z:")
    for d in sorted(packets.keys()):
        phi = euler_phi(d)
        match_str = "OK" if len(packets[d]) == phi else "MISMATCH"
        label = (
            "trivial (gauge)"
            if d == 1
            else (f"single-prime (V)" if is_single_prime(d) else "cross-prime (M)")
        )
        print(
            f"    H_{d:>2} ({label}, dim={len(packets[d]):>2}; phi({d})={phi}): "
            f"{packets[d]}  [{match_str}]"
        )
    print()


