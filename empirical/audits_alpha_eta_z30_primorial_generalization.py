# Section D.  Pontryagin character orthogonality verification
# ----------------------------------------------------------------------------
def verify_pontryagin_orthogonality(N: int, V_idx: list[int], M_idx: list[int]):
    """Build the character matrix on Z/N: char[j, k] = exp(2*pi*i*k*j/N)/sqrt(N).
    Build V- and M- projectors as sums of |chi_k><chi_k|.  Verify V_proj M_proj
    = 0 to machine precision."""
    char = np.zeros((N, N), dtype=complex)
    for j in range(N):
        for k in range(N):
            char[j, k] = np.exp(2j * np.pi * k * j / N) / np.sqrt(N)

    V_proj = np.zeros((N, N), dtype=complex)
    for k in V_idx:
        v = char[:, k]
        V_proj += np.outer(v, v.conj())

    M_proj = np.zeros((N, N), dtype=complex)
    for k in M_idx:
        v = char[:, k]
        M_proj += np.outer(v, v.conj())

    overlap = V_proj @ M_proj
    overlap_fro = float(np.linalg.norm(overlap))

    # Also verify projector properties: V_proj^2 = V_proj, V_proj† = V_proj
    V_idemp = float(np.linalg.norm(V_proj @ V_proj - V_proj))
    V_herm = float(np.linalg.norm(V_proj - V_proj.conj().T))
    M_idemp = float(np.linalg.norm(M_proj @ M_proj - M_proj))
    M_herm = float(np.linalg.norm(M_proj - M_proj.conj().T))

    return {
        "overlap_fro": overlap_fro,
        "V_idemp_err": V_idemp,
        "V_herm_err": V_herm,
        "M_idemp_err": M_idemp,
        "M_herm_err": M_herm,
        "V_rank": float(np.trace(V_proj).real),  # dim of V sub-Hilbert-space
        "M_rank": float(np.trace(M_proj).real),  # dim of M sub-Hilbert-space
    }


