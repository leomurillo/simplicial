# Section C.  Closing triples (cubic AC selection rule)
# ----------------------------------------------------------------------------
def enumerate_closing_multisets(N: int) -> list[tuple[int, int, int]]:
    """All unordered multisets (a <= b <= c) from {1,...,N-1} with
    a+b+c == 0 (mod N).  Returns list of (a,b,c) triples sorted."""
    dynamical = list(range(1, N))
    triples = []
    for a, b, c in combinations_with_replacement(dynamical, 3):
        if (a + b + c) % N == 0:
            triples.append((a, b, c))
    return triples


def classify_triple(
    triple: tuple[int, int, int], V_idx: list[int], M_idx: list[int]
) -> str:
    cats = []
    V_set = set(V_idx)
    M_set = set(M_idx)
    for x in triple:
        if x in V_set:
            cats.append("V")
        elif x in M_set:
            cats.append("M")
        else:
            cats.append("?")
    cats.sort()
    return "".join(cats)


