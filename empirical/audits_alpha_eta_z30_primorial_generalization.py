    dim_M = len(M_idx)
    dim_dyn = N - 1  # excludes trivial k=0

    print(f"  V (single-prime conductor packets, dim {dim_V}): {V_idx}")
    print(f"  M (cross-prime conductor packets,  dim {dim_M}): {M_idx}")
    print(f"  trivial gauge (excluded from dynamics): {triv_idx}")
    print(f"  dim_dynamical = {dim_dyn} (= V + M + 0 = {dim_V} + {dim_M})")
    if dim_V + dim_M != dim_dyn:
        print(f"  WARNING: V + M != dim_dynamical")
    ratio_VM = dim_V / dim_M if dim_M > 0 else float("inf")
    print(f"  V/M dimensional ratio = {dim_V}/{dim_M} = {ratio_VM:.6f}")
    print()

    # C. Closing multisets
    triples = enumerate_closing_multisets(N)
    total = len(triples)
    classes = Counter(classify_triple(t, V_idx, M_idx) for t in triples)
    print(f"  Closing unordered multisets {{a<=b<=c}} from {{1,...,{N-1}}}")
    print(f"  with a+b+c == 0 (mod {N}):  total = {total}")
    print()
    print("  Partition by V/M content (sorted within each multiset):")
    for cl in sorted(classes.keys()):
        cnt = classes[cl]
        pct = 100.0 * cnt / total if total else 0.0
        print(f"    {cl:>5}: {cnt:>5}  ({pct:>5.2f}%)")
    print()

    # Pure-V and pure-M counts
    pure_V = classes.get("VVV", 0)
    pure_M = classes.get("MMM", 0)
    cross = total - pure_V - pure_M
    print(f"  Conductor Capacity Bound (Paper 48 C2):")
    print(f"    pure-V multisets:    {pure_V}/{total}  =  Capacity_V = "
          f"{pure_V/total if total else 0:.6f}")
    print(f"    pure-M multisets:    {pure_M}/{total}")
    print(f"    cross VM multisets:  {cross}/{total}")
    print()

    # List pure-V triples (small)
    if pure_V > 0:
        print(f"  Pure-V multisets (explicit):")
        for t in triples:
            if classify_triple(t, V_idx, M_idx) == "VVV":
                print(f"    {t}  (sum = {sum(t)})")
        print()

    # D. Pontryagin orthogonality
    print(f"  Pontryagin character orthogonality (Paper 47 C3):")
    pq = verify_pontryagin_orthogonality(N, V_idx, M_idx)
    print(f"    V_proj rank (= dim_V):  {pq['V_rank']:.6f}   "
          f"(expected: {dim_V})")
    print(f"    M_proj rank (= dim_M):  {pq['M_rank']:.6f}   "
          f"(expected: {dim_M})")
    print(f"    ||V_proj^2 - V_proj||_F: {pq['V_idemp_err']:.6e}  "
          f"(projector idempotence)")
    print(f"    ||V_proj^dagger - V_proj||_F: {pq['V_herm_err']:.6e}  "
          f"(projector hermiticity)")
    print(f"    ||M_proj^2 - M_proj||_F: {pq['M_idemp_err']:.6e}")
    print(f"    ||M_proj^dagger - M_proj||_F: {pq['M_herm_err']:.6e}")
    print(f"    ||V_proj * M_proj||_F: {pq['overlap_fro']:.6e}  "
          f"<<< V perp M overlap norm")
    print()

    if reference_anchors:
        print("  Anchor checks (Z/6 reference):")
        for key, expected, observed in reference_anchors:
            if isinstance(expected, float):
                ok = abs(expected - observed) < 1e-9
                ok_str = "OK" if ok else "MISMATCH"
                print(f"    {key}: observed {observed:.6f}, expected {expected:.6f}  [{ok_str}]")
            else:
                ok = expected == observed
                ok_str = "OK" if ok else "MISMATCH"
                print(f"    {key}: observed {observed}, expected {expected}  [{ok_str}]")
        print()

    return {
        "N": N,
        "dim_V": dim_V,
        "dim_M": dim_M,
        "total_triples": total,
        "pure_V": pure_V,
        "pure_M": pure_M,
        "cross": cross,
        "capacity_V": pure_V / total if total else 0.0,
        "V_idx": V_idx,
        "M_idx": M_idx,
        "pontryagin_overlap_fro": pq["overlap_fro"],
        "pontryagin_V_idemp": pq["V_idemp_err"],
        "pontryagin_M_idemp": pq["M_idemp_err"],
    }


