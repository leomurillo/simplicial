"""Variational consistency audit for Paper 28, Theorem 7.2.

This audit tests whether the force-level reference implementation

    rdot = v,   pdot = Pi(K_CH(Deta v, Deta v))

is actually generated by the natural reduced-channel Lagrangian

    L_ref(q, qdot) = 1/2 eps^2 sum_alpha qdot_alpha^2
                    + 1/3 eps^2 sum_alpha q_alpha qdot_alpha^2.

The second term is the minimal diagonal cubic-channel model matching the
reference C^alpha_{alpha alpha}=1 convention used in the E6 dynamics audit.
If the Euler-Lagrange acceleration does not match F/m, E3_red remains blocked:
the moment-map force is not yet tied to this reduced variational model.
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

import numpy as np


def center_state(r: np.ndarray, p: np.ndarray, masses: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    total_m = float(np.sum(masses))
    r_cm = np.sum(masses[:, None] * r, axis=0) / total_m
    p_cm = np.sum(p, axis=0) / total_m
    return r - r_cm, p - masses[:, None] * p_cm


def initial_state(seed: int, masses: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    rng = np.random.default_rng(seed)
    r = rng.normal(size=(3, 3))
    r[2] += np.array([0.35, -0.21, 0.41])
    p = 0.15 * rng.normal(size=(3, 3))
    return center_state(r, p, masses)


def side_data(r: np.ndarray, delta: float) -> dict:
    d12 = np.linalg.norm(r[0] - r[1])
    d23 = np.linalg.norm(r[1] - r[2])
    d31 = np.linalg.norm(r[2] - r[0])
    s12 = math.sqrt(d12 * d12 + delta * delta)
    s23 = math.sqrt(d23 * d23 + delta * delta)
    s31 = math.sqrt(d31 * d31 + delta * delta)
    area16 = (
        2 * d12 * d12 * d23 * d23
        + 2 * d23 * d23 * d31 * d31
        + 2 * d31 * d31 * d12 * d12
        - d12**4
        - d23**4
        - d31**4
    )
    area16_reg = (
        2 * s12 * s12 * s23 * s23
        + 2 * s23 * s23 * s31 * s31
        + 2 * s31 * s31 * s12 * s12
        - s12**4
        - s23**4
        - s31**4
    )
    perimeter_sq = max((d12 + d23 + d31) ** 2, 1.0e-300)
    quality = math.sqrt(max(area16, 0.0)) / perimeter_sq
    return {"s": np.array([s12, s23, s31]), "area16_reg": area16_reg, "quality": quality}


def q_values(r: np.ndarray, delta: float) -> np.ndarray:
    data = side_data(r, delta)
    s12, s23, s31 = data["s"]
    if data["area16_reg"] <= 0:
        raise ValueError("regularized Heron area is nonpositive")
    return np.array(
        [
            math.log(s12 + s23 + s31),
            0.5 * math.log(data["area16_reg"]),
            math.log(s12 * s23 * s31),
        ]
    )


def numerical_jacobian(fn, x: np.ndarray, step: float) -> np.ndarray:
    flat = x.reshape(-1)
    y_size = fn(x).size
    jac = np.zeros((y_size, flat.size))
    for idx in range(flat.size):
        xp = flat.copy()
        xm = flat.copy()
        xp[idx] += step
        xm[idx] -= step
        jac[:, idx] = (fn(xp.reshape(x.shape)) - fn(xm.reshape(x.shape))) / (2 * step)
    return jac


def q_jacobian(r: np.ndarray, delta: float, fd_step: float) -> np.ndarray:
    return numerical_jacobian(lambda x: q_values(x, delta), r, fd_step)


def lagrangian(r_flat: np.ndarray, v_flat: np.ndarray, args: argparse.Namespace) -> float:
    r = r_flat.reshape(3, 3)
    q = q_values(r, args.delta)
    jac = q_jacobian(r, args.delta, args.fd_step)
    qdot = jac @ v_flat
    return float(0.5 * args.epsilon**2 * np.dot(qdot, qdot) + (args.epsilon**2 / 3.0) * np.dot(q, qdot * qdot))


def grad_r(r_flat: np.ndarray, v_flat: np.ndarray, args: argparse.Namespace) -> np.ndarray:
    out = np.zeros_like(r_flat)
    for idx in range(r_flat.size):
        rp = r_flat.copy()
        rm = r_flat.copy()
        rp[idx] += args.variation_step
        rm[idx] -= args.variation_step
        out[idx] = (lagrangian(rp, v_flat, args) - lagrangian(rm, v_flat, args)) / (2 * args.variation_step)
    return out


def grad_v(r_flat: np.ndarray, v_flat: np.ndarray, args: argparse.Namespace) -> np.ndarray:
    out = np.zeros_like(v_flat)
    for idx in range(v_flat.size):
        vp = v_flat.copy()
        vm = v_flat.copy()
        vp[idx] += args.variation_step
        vm[idx] -= args.variation_step
        out[idx] = (lagrangian(r_flat, vp, args) - lagrangian(r_flat, vm, args)) / (2 * args.variation_step)
    return out


def jacobian_grad_v_r(r_flat: np.ndarray, v_flat: np.ndarray, args: argparse.Namespace) -> np.ndarray:
    out = np.zeros((v_flat.size, r_flat.size))
    for idx in range(r_flat.size):
        rp = r_flat.copy()
        rm = r_flat.copy()
        rp[idx] += args.variation_step
        rm[idx] -= args.variation_step
        out[:, idx] = (grad_v(rp, v_flat, args) - grad_v(rm, v_flat, args)) / (2 * args.variation_step)
    return out


def hessian_vv(r_flat: np.ndarray, v_flat: np.ndarray, args: argparse.Namespace) -> np.ndarray:
    out = np.zeros((v_flat.size, v_flat.size))
    for idx in range(v_flat.size):
        vp = v_flat.copy()
        vm = v_flat.copy()
        vp[idx] += args.variation_step
        vm[idx] -= args.variation_step
        out[:, idx] = (grad_v(r_flat, vp, args) - grad_v(r_flat, vm, args)) / (2 * args.variation_step)
    return 0.5 * (out + out.T)


def projected_force(r: np.ndarray, p: np.ndarray, masses: np.ndarray, args: argparse.Namespace) -> np.ndarray:
    jac = q_jacobian(r, args.delta, args.fd_step).reshape(3, 3, 3)
    v = p / masses[:, None]
    qdot = np.einsum("abi,bi->a", jac, v)
    force = np.zeros_like(r)
    for alpha in range(3):
        force += args.epsilon**2 * jac[alpha] * qdot[alpha] ** 2
    return force


def variational_acceleration(r: np.ndarray, p: np.ndarray, masses: np.ndarray, args: argparse.Namespace) -> np.ndarray:
    r_flat = r.reshape(-1)
    v_flat = (p / masses[:, None]).reshape(-1)
    h_vv = hessian_vv(r_flat, v_flat, args)
    mixed = jacobian_grad_v_r(r_flat, v_flat, args)
    rhs = grad_r(r_flat, v_flat, args) - mixed @ v_flat
    accel, *_ = np.linalg.lstsq(h_vv, rhs, rcond=args.lstsq_rcond)
    return accel.reshape(3, 3)


def audit(args: argparse.Namespace) -> dict:
    masses = np.array(args.masses, dtype=float)
    samples = []
    kills = []
    for offset in range(args.samples):
        r, p = initial_state(args.seed + offset, masses)
        quality = side_data(r, args.delta)["quality"]
        if quality < args.min_shape_quality:
            samples.append({"seed": args.seed + offset, "evaluated": False, "shape_quality": quality})
            continue
        force_accel = projected_force(r, p, masses, args) / masses[:, None]
        var_accel = variational_acceleration(r, p, masses, args)
        residual = var_accel - force_accel
        denom = max(float(np.linalg.norm(var_accel)), float(np.linalg.norm(force_accel)), 1.0e-300)
        rel = float(np.linalg.norm(residual) / denom)
        samples.append(
            {
                "seed": args.seed + offset,
                "evaluated": True,
                "shape_quality": quality,
                "relative_acceleration_residual": rel,
                "variational_acceleration_norm": float(np.linalg.norm(var_accel)),
                "projected_force_acceleration_norm": float(np.linalg.norm(force_accel)),
            }
        )
    evaluated = [s for s in samples if s["evaluated"]]
    if not evaluated:
        kills.append("no samples passed the nondegenerate-shape gate")
        max_rel = float("inf")
    else:
        max_rel = max(s["relative_acceleration_residual"] for s in evaluated)
        if max_rel > args.consistency_tol:
            kills.append("projected force is not Euler-Lagrange for L_ref within tolerance")

    return {
        "claim_tested": "force-level projection equals Euler-Lagrange dynamics of L_ref",
        "kill_condition": f"relative acceleration residual > {args.consistency_tol}",
        "parameters": {
            key: str(value) if isinstance(value, Path) else value
            for key, value in vars(args).items()
        },
        "samples": samples,
        "summary": {
            "status": "PASS" if not kills else "KILL",
            "E3_red_status": "EVALUABLE_ONLY_IF_STATUS_PASS",
            "max_relative_acceleration_residual": max_rel,
            "kills": kills,
        },
    }


def write_report(result: dict, out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    summary = result["summary"]
    lines = [
        "# Three-Body Ternary Variational Consistency Audit",
        "",
        "This audit checks whether the implemented projected force is generated by",
        "the reference reduced-channel Lagrangian L_ref. If it fails, E3_red",
        "remains blocked for that force implementation.",
        "",
        f"- Claim tested: {result['claim_tested']}",
        f"- Kill condition: {result['kill_condition']}",
        "",
        "## Summary",
        "",
        f"- Status: {summary['status']}",
        f"- E3_red status: {summary['E3_red_status']}",
        f"- max relative acceleration residual: {summary['max_relative_acceleration_residual']:.6e}",
        f"- kills: {summary['kills']}",
        "",
        "## Samples",
        "",
        "| seed | used | quality | relative residual | EL accel norm | force accel norm |",
        "|---:|:---:|---:|---:|---:|---:|",
    ]
    for sample in result["samples"]:
        if not sample["evaluated"]:
            lines.append(f"| {sample['seed']} | no | {sample['shape_quality']:.6e} | -- | -- | -- |")
        else:
            lines.append(
                "| {seed} | yes | {shape_quality:.6e} | {relative_acceleration_residual:.6e} | "
                "{variational_acceleration_norm:.6e} | {projected_force_acceleration_norm:.6e} |".format(
                    **sample
                )
            )
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--masses", nargs=3, type=float, default=[1.0, 1.25, 0.85])
    parser.add_argument("--delta", type=float, default=0.15)
    parser.add_argument("--epsilon", type=float, default=1.0e-3)
    parser.add_argument("--seed", type=int, default=2863)
    parser.add_argument("--samples", type=int, default=3)
    parser.add_argument("--fd-step", type=float, default=1.0e-6)
    parser.add_argument("--variation-step", type=float, default=2.0e-5)
    parser.add_argument("--min-shape-quality", type=float, default=1.0e-3)
    parser.add_argument("--consistency-tol", type=float, default=1.0e-3)
    parser.add_argument("--lstsq-rcond", type=float, default=1.0e-10)
    parser.add_argument(
        "--report",
        type=Path,
        default=Path("empirical/reports/three_body_ternary_variational_consistency_audit.md"),
    )
    parser.add_argument(
        "--json",
        type=Path,
        default=Path("empirical/reports/three_body_ternary_variational_consistency_audit.json"),
    )
    args = parser.parse_args()

    result = audit(args)
    write_report(result, args.report)
    args.json.parent.mkdir(parents=True, exist_ok=True)
    args.json.write_text(json.dumps(result, indent=2), encoding="utf-8")
    print(json.dumps(result["summary"], indent=2))


if __name__ == "__main__":
    main()
