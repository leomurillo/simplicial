"""Exact verifier for the cyclic B0 balance-transfer descent theorem.

For C_N, a reciprocal Fourier support S activates conductors cond(k).  The
balance-transfer closure is the unique subgroup generated by S:

    D_N(S) = {k != 0 : cond(k) divides lcm(cond(S))}.

This script verifies the finite set identities behind the theorem across
cyclic rows and writes a compact certificate report.
"""

from __future__ import annotations

import argparse
import json
import math
from itertools import combinations
from pathlib import Path
from typing import Any


DEFAULT_JSON = Path("empirical/reports/cyclic_b0_descent_theorem.json")
DEFAULT_REPORT = Path("empirical/reports/cyclic_b0_descent_theorem.md")


def divisors(n: int) -> list[int]:
    return [value for value in range(1, n + 1) if n % value == 0]


def conductor(n: int, k: int) -> int:
    k %= n
    if k == 0:
        return 1
    return n // math.gcd(n, k)


def euler_phi(n: int) -> int:
    count = 0
    for value in range(1, n + 1):
        if math.gcd(value, n) == 1:
            count += 1
    return count


def modes_with_conductor(n: int, d: int) -> set[int]:
    return {mode for mode in range(1, n) if conductor(n, mode) == d}


def closure_from_conductor_lcm(n: int, conductor_lcm: int) -> set[int]:
    return {
        mode
        for mode in range(1, n)
        if conductor_lcm % conductor(n, mode) == 0
    }


def subgroup_generated_by_support(n: int, support: set[int]) -> set[int]:
    if not support:
        return set()
    step = math.gcd(n, *support)
    return {mode for mode in range(step, n, step)}


def closure_from_support(n: int, support: set[int]) -> set[int]:
    if not support:
        return set()
    conductor_lcm = math.lcm(*(conductor(n, mode) for mode in support))
    return closure_from_conductor_lcm(n, conductor_lcm)


def is_closed(n: int, support: set[int]) -> bool:
    for left in support:
        for right in support:
            target = (left + right) % n
            if target != 0 and target not in support:
                return False
    return True


def conductor_subset_certificates(n: int) -> list[dict[str, Any]]:
    conductors = divisors(n)[1:]
    rows: list[dict[str, Any]] = []
    for size in range(1, len(conductors) + 1):
        for subset in combinations(conductors, size):
            conductor_lcm = math.lcm(*subset)
            support = {min(modes_with_conductor(n, d)) for d in subset}
            descent = closure_from_support(n, support)
            by_lcm = closure_from_conductor_lcm(n, conductor_lcm)
            by_subgroup = subgroup_generated_by_support(n, support)
            if descent != by_lcm:
                raise AssertionError(f"C_{n} {subset}: lcm closure mismatch")
            if descent != by_subgroup:
                raise AssertionError(f"C_{n} {subset}: subgroup closure mismatch")
            if not is_closed(n, descent):
                raise AssertionError(f"C_{n} {subset}: descent closure is not closed")
            if closure_from_support(n, descent) != descent:
                raise AssertionError(f"C_{n} {subset}: descent closure is not idempotent")
            if len(descent) != conductor_lcm - 1:
                raise AssertionError(f"C_{n} {subset}: closure size is not M-1")
            expected_size = sum(euler_phi(d) for d in divisors(conductor_lcm)[1:])
            if len(descent) != expected_size:
                raise AssertionError(f"C_{n} {subset}: phi-size mismatch")
            rows.append(
                {
                    "active_conductors": list(subset),
                    "combined_conductor": conductor_lcm,
                    "descent_size": len(descent),
                    "resource_ratio": len(descent) / (n - 1),
                    "descent_modes": sorted(descent),
                }
            )
    return rows


def row(n: int) -> dict[str, Any]:
    closure_classes = [
        {
            "combined_conductor": d,
            "descent_size": d - 1,
            "resource_ratio": (d - 1) / (n - 1),
            "included_conductors": divisors(d)[1:],
        }
        for d in divisors(n)[1:]
    ]
    subset_rows = conductor_subset_certificates(n)
    proper = [item for item in closure_classes if item["combined_conductor"] < n]
    if not proper:
        reading = "prime control: every nonzero support descends to the full family"
    elif len(divisors(n)) == 2:
        reading = "prime control"
    elif all(d % min(divisors(n)[1:]) == 0 for d in divisors(n)[1:]):
        reading = "prime-power ladder"
    else:
        reading = "mixed-prime balance-transfer ladder"

    return {
        "group": f"C_{n}",
        "n": n,
        "conductors": divisors(n)[1:],
        "closure_classes": closure_classes,
        "conductor_subset_checks": len(subset_rows),
        "proper_closure_count": len(proper),
        "best_proper_resource_ratio": min(
            (item["resource_ratio"] for item in proper),
            default=1.0,
        ),
        "reading": reading,
    }


def build_payload(min_n: int, max_n: int) -> dict[str, Any]:
    rows = [row(n) for n in range(min_n, max_n + 1)]
    return {
        "theorem": (
            "For C_N and nonempty reciprocal Fourier support S, the B0 "
            "balance-transfer closure D_N(S) is the nonzero part of the "
            "unique subgroup generated by S, equivalently the modes whose "
            "conductors divide lcm(cond(S))."
        ),
        "minimality": (
            "Any support with zero reciprocal projection for generic S and "
            "zero descent-balance cost must contain D_N(S).  D_N(S) has zero "
            "projection, closure, and balance costs, so it is the unique "
            "minimum-resource zero-structural-cost support."
        ),
        "rows": rows,
    }


def write_json(payload: dict[str, Any], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")


def render_markdown(payload: dict[str, Any]) -> str:
    lines = [
        "# Cyclic B0 Balance-Transfer Descent Theorem",
        "",
        "## Theorem",
        "",
        payload["theorem"],
        "",
        "## Minimality",
        "",
        payload["minimality"],
        "",
        "## Certified Rows",
        "",
        "| group | conductors | closure classes | subset checks | proper closures | best proper resource | reading |",
        "|---|---|---:|---:|---:|---:|---|",
    ]
    for item in payload["rows"]:
        lines.append(
            "| {group} | {conductors} | {classes} | {checks} | {proper} | {ratio:.6f} | {reading} |".format(
                group=item["group"],
                conductors=", ".join(str(x) for x in item["conductors"]),
                classes=len(item["closure_classes"]),
                checks=item["conductor_subset_checks"],
                proper=item["proper_closure_count"],
                ratio=item["best_proper_resource_ratio"],
                reading=item["reading"],
            )
        )

    lines += [
        "",
        "## Closure Class Details",
        "",
    ]
    for item in payload["rows"]:
        lines += [f"### {item['group']}", ""]
        lines += [
            "| combined conductor M | descent size | resource ratio | included conductors |",
            "|---:|---:|---:|---|",
        ]
        for closure in item["closure_classes"]:
            lines.append(
                "| {M} | {size} | {ratio:.6f} | {conductors} |".format(
                    M=closure["combined_conductor"],
                    size=closure["descent_size"],
                    ratio=closure["resource_ratio"],
                    conductors=", ".join(str(x) for x in closure["included_conductors"]),
                )
            )
        lines.append("")
    return "\n".join(lines)


def write_report(payload: dict[str, Any], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_markdown(payload) + "\n", encoding="utf-8")


def check_payload(payload: dict[str, Any], path: Path) -> None:
    recorded = json.loads(path.read_text(encoding="utf-8"))
    if recorded != payload:
        raise AssertionError(f"payload differs from {path}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--min-n", type=int, default=2)
    parser.add_argument("--max-n", type=int, default=48)
    parser.add_argument("--json", type=Path, default=DEFAULT_JSON)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    parser.add_argument("--check", type=Path, default=None)
    args = parser.parse_args()

    if args.min_n < 2:
        raise ValueError("--min-n must be at least 2")
    if args.max_n < args.min_n:
        raise ValueError("--max-n must be >= --min-n")

    payload = build_payload(args.min_n, args.max_n)
    if args.check is not None:
        check_payload(payload, args.check)
        print(f"checked {args.check}")
        return

    write_json(payload, args.json)
    write_report(payload, args.report)
    print(f"wrote {args.report}")
    print(f"wrote {args.json}")


if __name__ == "__main__":
    main()
