"""
NEXT-ROUND MOVE (1): both potentials of the Weil form in the same convex-analytic currency.

N14 proved the ARCHIMEDEAN side of the Weil form is a relative entropy D(P_beta||u) (Gibbs-positive).
This probe renders the PRIME side as the matching object: a Bregman divergence / relative entropy of the
convex log-partition Phi(s) = log zeta(s) -- the free energy of the "zeta distribution" P_s(n) = n^{-s}/zeta(s).
The classical Euler-product note (Annamalai / Euler 1737) is exactly the certificate that this prime
potential is SEPARABLE over primes (independent prime-exponent coordinates) = T0 Thm 4.7 = N9 cross-prime
fusion closure.

What is established here (all exact-arithmetic, mpmath/sympy, NO torch):

  A. PRIME POTENTIAL.  Phi(s)=log zeta(s) is a convex log-partition: Phi'=zeta'/zeta = -sum Lambda(n) n^{-s}
     (the generator of the Weil-form prime term); Phi'' = Var_{P_s}(log n) >= 0 (Cauchy-Schwarz = Fisher).
  B. SEPARABILITY = EULER PRODUCT = T0 Thm 4.7.  Phi(s)=sum_p -log(1-p^{-s}) and
     Phi''(s)=sum_p (log p)^2 p^{-s}/(1-p^{-s})^2 -- per-prime geometric variances, ZERO cross-prime
     covariance (the prime-exponent coordinates k_p are independent under P_s). This is what the note proves.
  C. PRIME SIDE AS RELATIVE ENTROPY.  D(P_{s1}||P_{s2}) = B_Phi(s2||s1)
     = Phi(s2)-Phi(s1)-Phi'(s1)(s2-s1) >= 0, = 0 iff s1=s2. The exact analog of N14's archimedean D(P_beta||u).
  D. THE TWO POTENTIALS SIDE BY SIDE.  Weil = (archimedean relative entropy, N14) - (prime free energy log zeta);
     a difference of convex potentials. On Re(s)>1 it is trivially signed (Euler product nonvanishing -> no
     zeros); RH is the SIGN of the difference under continuation to the critical line s=1/2 (the s/(1-s) edge
     of N5, crossable only by the Gamma-factor of T15). We locate RH; we do not claim it.
  E. FUSION-SIGHTED (N9 control).  zeta has cross-prime defect 0; Davenport-Heilbronn (functional equation,
     off-line zeros) has defect ~1.081 -> NO Euler product -> NO separable convex potential. So the bridge
     cannot be impersonated by the standard counterexample.

Honest scope: this proves both sides are convex potentials in the SAME currency and locates RH as their
domination across s=1/2. It does NOT prove that domination (= RH).
"""
import mpmath as mp
import sympy as sp

mp.mp.dps = 30

# ----------------------------------------------------------------------------------------------
# Exact zeta-family objects (mpmath; zeta derivatives are exact, no truncation)
# ----------------------------------------------------------------------------------------------
def Phi(s):                       # log-partition of the zeta distribution
    return mp.log(mp.zeta(s))
def dPhi(s):                      # Phi'(s) = zeta'/zeta = -sum Lambda(n) n^{-s}  (mean parameter, with sign)
    return mp.zeta(s, 1, 1) / mp.zeta(s)
def ddPhi(s):                     # Phi''(s) = zeta''/zeta - (zeta'/zeta)^2 = Var_{P_s}(log n) = Fisher
    z, z1, z2 = mp.zeta(s), mp.zeta(s, 1, 1), mp.zeta(s, 1, 2)
    return z2 / z - (z1 / z) ** 2

PRIMES = list(sp.primerange(2, 200000))   # for the per-prime (separability) sums

def Phi_euler(s):                 # sum_p -log(1 - p^{-s})  (Euler product as log-partition factorization)
    return mp.fsum(-mp.log(1 - mp.mpf(p) ** (-s)) for p in PRIMES)
def ddPhi_perprime(s):            # sum_p (log p)^2 p^{-s} / (1 - p^{-s})^2  (sum of per-prime geom. variances)
    acc = mp.mpf(0)
    for p in PRIMES:
        x = mp.mpf(p) ** (-s)
        acc += (mp.log(p) ** 2) * x / (1 - x) ** 2
    return acc
def vonmangoldt_dirichlet(s, nmax=200000):   # sum_{n>=2} Lambda(n) n^{-s}  == -Phi'(s)
    acc = mp.mpf(0)
    for p in PRIMES:
        pk = p
        while pk <= nmax:
            acc += mp.log(p) * mp.mpf(pk) ** (-s)
            pk *= p
    return acc

# ----------------------------------------------------------------------------------------------
print("=" * 94)
print("A. PRIME POTENTIAL  Phi(s)=log zeta(s) is a CONVEX log-partition (Phi''=Var(log n)=Fisher>0)")
print("=" * 94)
print(f"  {'s':>5} {'Phi=log zeta':>16} {'dPhi=zp/z':>17} {'ddPhi=Var(log n)':>17} {'convex?':>8}")
okA = True
for s in (mp.mpf('1.5'), mp.mpf(2), mp.mpf(3), mp.mpf(4)):
    v = ddPhi(s); okA = okA and (v > 0)
    print(f"  {mp.nstr(s,3):>5} {mp.nstr(Phi(s),10):>16} {mp.nstr(dPhi(s),10):>17} {mp.nstr(v,10):>17} {str(v>0):>8}")
print(f"  --> log zeta convex on (1,inf) (Cauchy-Schwarz zeta*zeta'' >= zeta'^2): {okA}")

print("=" * 94)
print("   Phi'(s) = -sum_n Lambda(n) n^{-s}  (the prime side of the Weil form is generated by Phi')")
print("=" * 94)
okA2 = True
for s in (mp.mpf(2), mp.mpf(3), mp.mpf(4)):
    lhs = dPhi(s); rhs = -vonmangoldt_dirichlet(s)
    err = abs(lhs - rhs)
    tol = mp.mpf('1e-4') if s == 2 else mp.mpf('1e-9')   # s=2 truncation-limited (primes<2e5); s>=3 tight
    okA2 = okA2 and (err < tol)
    print(f"  s={mp.nstr(s,2):>3}:  zeta'/zeta = {mp.nstr(lhs,12):>16}   -sum Lambda(n)n^-s = {mp.nstr(rhs,12):>16}   err={mp.nstr(err,3)}")
print(f"  --> the Weil-form prime generator IS Phi' (von Mangoldt = -Phi'): {okA2}")

print("=" * 94)
print("B. SEPARABILITY = EULER PRODUCT = T0 Thm 4.7  (independence of prime-exponent coordinates)")
print("=" * 94)
print(f"  {'s':>5} {'Phi exact':>15} {'sum_p -log(1-p^-s)':>20} {'err':>10} | {'ddPhi exact':>13} {'sum_p Var_p':>14} {'err':>10}")
okB = True
for s in (mp.mpf('1.5'), mp.mpf(2), mp.mpf(3), mp.mpf(4)):
    pe, pee = Phi_euler(s), ddPhi_perprime(s)
    e1, e2 = abs(Phi(s) - pe), abs(ddPhi(s) - pee)
    # truncation-limited: Phi-level tight for s>=2; variance-level looser at small s (tail ~ logX/X)
    tolPhi = mp.mpf('1e-6') if s >= 2 else mp.mpf('1e-3')
    tolVar = mp.mpf('1e-3') if s == 2 else (mp.mpf('1e-1') if s < 2 else mp.mpf('1e-7'))
    ok = (e1 < tolPhi) and (e2 < tolVar); okB = okB and ok
    print(f"  {mp.nstr(s,3):>5} {mp.nstr(Phi(s),9):>15} {mp.nstr(pe,9):>20} {mp.nstr(e1,2):>10} | "
          f"{mp.nstr(ddPhi(s),8):>13} {mp.nstr(pee,8):>14} {mp.nstr(e2,2):>10}")
print("  --> log zeta = sum_p (local), Var = sum_p Var_p (no cross terms). Residual = truncation (primes<2e5),")
print(f"      shrinks as s grows away from the edge s=1. Euler product = ANOVA separability (T0 Thm 4.7): {okB}")

print("=" * 94)
print("C. PRIME SIDE AS RELATIVE ENTROPY  D(P_s1||P_s2) = Bregman B_Phi(s2||s1) >= 0  (analog of N14)")
print("=" * 94)
def D_bregman(s1, s2):            # closed form, exact
    return Phi(s2) - Phi(s1) - dPhi(s1) * (s2 - s1)
def D_direct(s1, s2, nmax=60000): # truncated KL of the actual zeta distributions (cross-validation)
    ns = [mp.mpf(n) for n in range(1, nmax + 1)]
    w1 = [n ** (-s1) for n in ns]; Z1 = mp.fsum(w1)
    w2 = [n ** (-s2) for n in ns]; Z2 = mp.fsum(w2)
    return mp.fsum((wi / Z1) * mp.log((wi / Z1) / (wj / Z2)) for wi, wj in zip(w1, w2))
print(f"  {'(s1,s2)':>12} {'D Bregman (exact)':>20} {'D direct KL (trunc)':>21} {'err':>10} {'>=0?':>5}")
okC = True
for (s1, s2) in [(mp.mpf('2.5'), mp.mpf(3)), (mp.mpf(3), mp.mpf('2.5')), (mp.mpf(3), mp.mpf(4)), (mp.mpf(3), mp.mpf(3))]:
    db = D_bregman(s1, s2); dd = D_direct(s1, s2)
    err = abs(db - dd); okC = okC and (db >= -mp.mpf('1e-20')) and (err < mp.mpf('1e-4'))
    print(f"  {f'({float(s1)},{float(s2)})':>12} {mp.nstr(db,12):>20} {mp.nstr(dd,12):>21} {mp.nstr(err,3):>10} {str(db>=-mp.mpf('1e-20')):>5}")
