# ---------------- Compute joint cumulants at dps=300 ----------------
M_MAX = 130

def joint_cumulant(m):
    total = mpf(0)
    for zs in self_dual.values():
        total += 2 * sum(z ** (-2 * m) for z in zs)
    for zs in non_self_dual_pairs.values():
        total += 2 * sum(z ** (-2 * m) for z in zs)
    return total

