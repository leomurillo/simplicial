"""Construct the finite GNS/Jacobi square-root operator for Pass-3 moments.

Given folded xi trace moments

    mu_n = ell_{n+1},

build the finite cyclic Hilbert space generated by polynomials modulo the
Hankel inner product

    <p,q> = sum p_i q_j mu_{i+j}.

In the orthonormal polynomial basis, multiplication by t is a symmetric
Jacobi/GNS compression J_N. Its eigenvalues are the Padé/Gauss nodes, and
the spectral weights of the cyclic vector are the quadrature weights.

This is the concrete finite square-root object behind the Hankel lock.
Numerical evidence only; not a proof of the native positivity theorem.
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

import mpmath as mp


mp.mp.dps = 100

PROBE_PATH = Path(__file__).with_name("probe_pass3_folded_xi_trace_model.py")
spec = importlib.util.spec_from_file_location("folded_probe", PROBE_PATH)
folded_probe = importlib.util.module_from_spec(spec)
assert spec.loader is not None
spec.loader.exec_module(folded_probe)
mp.mp.dps = 100
folded_probe.mp.mp.dps = 100


def trim(poly: list[mp.mpf]) -> list[mp.mpf]:
    out = list(poly)
    while len(out) > 1 and abs(out[-1]) < mp.mpf("1e-90"):
        out.pop()
    return out


def add(p: list[mp.mpf], q: list[mp.mpf], scale: mp.mpf = mp.mpf(1)) -> list[mp.mpf]:
    n = max(len(p), len(q))
    out = [mp.mpf(0)] * n
    for i in range(n):
        out[i] = (p[i] if i < len(p) else 0) + scale * (q[i] if i < len(q) else 0)
    return trim(out)


def scalar_mul(p: list[mp.mpf], c: mp.mpf) -> list[mp.mpf]:
    return trim([c * x for x in p])


def shift_t(p: list[mp.mpf]) -> list[mp.mpf]:
    return [mp.mpf(0)] + list(p)


def inner(p: list[mp.mpf], q: list[mp.mpf], mu: list[mp.mpf]) -> mp.mpf:
    total = mp.mpf(0)
    for i, pi in enumerate(p):
        for j, qj in enumerate(q):
            total += pi * qj * mu[i + j]
    return total


def orthonormal_polynomials(mu: list[mp.mpf], n: int) -> list[list[mp.mpf]]:
    polys: list[list[mp.mpf]] = []
    for degree in range(n):
        q = [mp.mpf(0)] * degree + [mp.mpf(1)]
        for p in polys:
            q = add(q, p, -inner(q, p, mu))
        norm2 = inner(q, q, mu)
        if norm2 <= 0:
            raise ValueError(f"nonpositive norm at degree {degree}: {norm2}")
        polys.append(scalar_mul(q, 1 / mp.sqrt(norm2)))
    return polys


def jacobi_from_moments(mu: list[mp.mpf], n: int) -> mp.matrix:
    polys = orthonormal_polynomials(mu, n)
    jmat = mp.matrix(n)
    for row in range(n):
        for col in range(n):
            jmat[row, col] = inner(polys[row], shift_t(polys[col]), mu)
    return jmat


def fmt(x: mp.mpf, digits: int = 18) -> str:
    return mp.nstr(x, digits)


def main() -> None:
    n = 10
    order = 2 * n + 4
    b = folded_probe.folded_coefficients(order + 2, radius=mp.mpf("1.0"), samples=2048)
    ell = folded_probe.formal_log_cumulants(b, order + 1)
    mu = ell

    jmat = jacobi_from_moments(mu, n)
    vals, vecs = mp.eigsy(jmat, eigvals_only=False)

    # eigsy returns ascending eigenvalues.
    atoms = []
    mu0 = mu[0]
    for idx, val in enumerate(vals):
        weight = mu0 * (vecs[0, idx] ** 2)
        atoms.append((mp.re(val), mp.re(weight), mp.re(weight / val)))
    atoms.sort(key=lambda row: row[0], reverse=True)

    known = []
    for k in range(1, n + 1):
        gamma = mp.im(mp.zetazero(k))
        known.append(1 / (gamma * gamma))

    gamma1 = mp.im(mp.zetazero(1))
    r = 1 / (gamma1 * gamma1)

    print(f"N={n}")
    print(f"R=gamma_1^-2 {fmt(r, 24)}")
    print(f"min eigenvalue {fmt(min(v for v, _, _ in atoms), 18)}")
    print(f"max eigenvalue {fmt(max(v for v, _, _ in atoms), 18)}")
    print(f"sum weights {fmt(sum(w for _, w, _ in atoms), 20)}")
    print(f"sum nodes   {fmt(sum(v for v, _, _ in atoms), 20)}")
    print(f"defect      {fmt(sum(abs(w - v) for v, w, _ in atoms), 20)}")

    print("\nJacobi/Helmert ladder coefficients")
    print("i   alpha_i=J[i,i]          beta_i=J[i,i+1]")
    for i in range(n):
        alpha = jmat[i, i]
        beta = jmat[i, i + 1] if i + 1 < n else mp.mpf(0)
        print(f"{i:2d}  {fmt(mp.re(alpha), 22):>24}  {fmt(mp.re(beta), 22):>24}")

    print("\na   node tau                  weight/node              nearest gamma_k^-2 rel.err")
    for a, (node, weight, ratio) in enumerate(atoms, start=1):
        nearest = min(known, key=lambda z: abs(node - z))
        rel = abs(node - nearest) / nearest
        print(
            f"{a:2d}  {fmt(node, 24):>28}  {fmt(ratio, 18):>22}  {mp.nstr(rel, 8)}"
        )


if __name__ == "__main__":
    main()
