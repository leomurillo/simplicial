def ldl(M):
    n = M.rows
    A = matrix(n, n)
    for i in range(n):
        for j in range(n):
            A[i, j] = M[i, j]
    diags = []
    for k in range(n):
        d = A[k, k]; diags.append(d)
        if d <= 0: return False, min(diags), k
        for i in range(k+1, n):
            f = A[i, k] / d
            for j in range(k+1, n):
                A[i, j] -= f * A[k, j]
    return True, min(diags), n

